<h2>Minutes/Summary of the Planning and Development Committee Meeting, August 24, 2026</h2>

<p>
  A Planning and Development Committee Meeting was held on
  <a href={Router.meeting("planning-and-development-committee-2026-08-24")}
    >Monday, August 24, 2026 at 6:00 PM in the City Council Chambers, Room 202</a
  >
</p>

<p>
  Committee Members Present: Committee Chair, John Michitson, Councilor Melissa Lewandowski,
  Councilor Devan Ferreira and Councilor Daniel Diodati
</p>

<p>Committee Members Absent: Councilor Catherine Rogers</p>

<p>Councilors Present: Councilor LePage</p>

<p>
  City Officials: Mayor Melinda Barrett, Robert Moore, Conservation Department, Jacki Byerley,
  Planning Director, City Solicitor Lisa Mead, Fire Chief Chris Cesati
</p>

<p>The following items were discussed:</p>

<ul>
  <li>
    <!-- The clerk's referred-documents list dates this referral 5/19/26; that
         sitting has no write-up here, so the link is to the sitting itself. -->
    <a href={Router.meeting("city-council-2026-05-19")}>Doc. 21-B</a> Motion by Councilor Sullivan to
    send for further discussion Chapter 255-Zoning Ordinance and Zoning Map &ndash; Battery Energy Storage
    Systems Overlay District (BESS) (review the objective site comparison before selecting a battery energy
    system overlay to understand how each candidate area performs from the perspective of public safety,
    environmental protections, infrastructure capacity, emergency response, water resources, surrounding
    land usage and municipal operations)
  </li>
</ul>

<p>
  Planning Director Jacki Byerley presented maps and departmental reviews of potential Battery
  Energy Storage System (BESS) zoning areas, including Computer Drive, Hilldale Avenue, Neck Road,
  Groveland Road, Amesbury Road, and Cross Road. She explained that departments applied the
  evaluation criteria differently based on their operational needs, so the scores were not directly
  comparable. Conservation favored Hilldale Avenue, while Engineering and Water/Wastewater favored
  Computer Drive, followed by Hilldale Avenue and Neck Road. Planning identified Amesbury Road as
  the strongest option among the business districts, and the Fire Department supported Amesbury Road
  for zoning purposes. Councilor Ferreira and City Solicitor Lisa Mead discussed whether clean
  energy projects could instead be addressed through special permit requirements, with City
  Solicitor Mead explaining that a zoning framework would provide the Council greater control over
  where projects are located. Councilor Lewandowski discussed the favorable characteristics of
  Hilldale Avenue, while Fire Chief Cesati noted concerns regarding site size, water flow, and
  access requirements. Chief Cesati stated that larger parcels would help avoid stacking and that
  all sites would require adequate fire access and water availability. Resident Christine Kwitchoff
  (14 Colby&rsquo;s Lane) clarified the minimum lot sizes for the three BESS tiers, and Conservation
  Agent Robert Moore discussed the potential to include the NETTS property with the Hilldale Avenue
  site. Rob Moore also raised environmental and water-supply concerns regarding Amesbury Road,
  including Blanding&rsquo;s turtle habitat, wetlands, and its proximity to Kenoza Lake and the
  Millvale Reservoir. Councilor Diodati expressed concerns about locating the district at the
  airport and the Groveland Road site due to new fields, while Councilor Lewandowski discussed the
  possibility of including the tractor-trailer facility with Hilldale Avenue to meet the 20-acre
  requirement.
</p>

<p>
  Corey O&rsquo;Neill (Haverhill resident) questioned whether October 1 is a deadline for the City
  to establish a BESS overlay district. City Solicitor Lisa Mead clarified that the City is not
  required to create an overlay, but without zoning in place, BESS facilities could potentially be
  proposed anywhere in the City. Corey O&rsquo;Neill stated that he believed additional time was
  needed to review the proposed locations, departmental assessments. He expressed concern about
  rushing the decision and raised questions regarding potential agreements between companies and
  City officials. Corey O&rsquo;Neill stated that he is not opposed to BESS technology but wants the
  City to find a balance that protects residents and the community.
</p>

<p>
  Christine Kwitchoff, 14 Colby&rsquo;s Lane, thanked the City departments for conducting the
  additional site reviews. She stated that it was a significant oversight at the May 19 meeting to
  present only one potential site and expressed appreciation for the opportunity for further public
  review.
</p>

<p>
  Anita Toscano, Corliss Hill Road, asked about the potential impacts of BESS facilities on the
  City&rsquo;s natural resources. She raised concerns regarding the amount of water that may be
  needed to address a battery fire and the potential environmental impacts and cleanup requirements
  in the event of a battery leak.
</p>

<p>
  City Solicitor Lisa Mead explained that BESS facilities do not require water for normal
  operations, but water is needed for emergency fire response, and the zoning ordinance requires an
  impervious catchment area beneath the facility. Fire Chief Cesati stated that battery fires
  require significant amounts of water to cool the batteries and prevent the fire from spreading,
  noting that a runaway battery must ultimately discharge its energy. Councilor Ferreira expressed
  support for the Hilldale Avenue site and suggested reducing the minimum acreage from 20 to 15
  acres. She also asked about potential host agreements or PILOT payments. City Solicitor Mead
  explained that such agreements could be pursued but could not be made a special permit
  requirement. Councilor Lewandowski asked about additional Fire Department training and equipment,
  and Chief Cesati stated that some equipment would need upgrading, training would be required and
  funded by the developer, and the department would meet applicable NFPA standards. Councilor
  Diodati discussed including the tractor-trailer facility with the Hilldale Avenue site to maintain
  the 20-acre requirement. City Solicitor Mead confirmed that the City Council&rsquo;s role is to
  ensure the use is permitted somewhere, not to determine whether a specific amount of available
  acreage exists. Chair Michitson stated that the committee could move forward with one site,
  recommend multiple sites, or seek additional information before making a decision.
</p>

<p>
  <em>
    Motion by Councilor Lewandowski to propose Hilldale Avenue as the recommended site for the
    district. Second by Councilor Diodati.
  </em>
</p>

<p>
  Jacki Byerley stated would you want a change made to the regulations requiring it to be 15 acres
  or do you want us to work on adding it so the total acreage of the area is 20 or more. Councilor
  Diodati stated I would like to see 20 acres. Jacki stated I will work with our GIS department.
  Chair Michitson stated that is part of the motion. Councilor Lewandowski stated sure.
</p>

<p>
  <em>
    Motion by Councilor Lewandowski to propose Hilldale Avenue as the recommended site for the
    district. The total acreage of the area will be 20 acres. Second by Councilor Diodati.
  </em><br />
  <em>PASSED</em> &mdash; <em>4 YEAS, 0 NAYS</em>
</p>

<p>
  City Solicitor Mead stated when you do bring it up, we will have to readvertise so the sooner you
  bring it up the better. It&rsquo;s a 21-day advertisement period.
</p>

<p>
  <em>Motion by Councilor Diodati to adjourn. Second by Councilor Lewandowski.</em><br />
  <em>PASSED</em> &mdash; <em>4 YEAS, 0 NAYS</em>
</p>

<p>Respectfully submitted,</p>

<p>
  John A. Michitson<br />
  Chairperson
</p>

