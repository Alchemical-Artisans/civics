<h2>Proposal for a Downtown Statue of John Greenleaf Whittier</h2>

<p>To be presented to the Haverhill City Council, October 27, 2026</p>

<h3>Purpose</h3>

<p>
  The Committee for a Downtown Statue of John Greenleaf Whittier respectfully seeks the Haverhill
  City Council's support for placing a statue of Whittier, with mention of his accomplishments, in
  an active downtown location. We thank members of the City Council for allowing us to speak
  tonight.
</p>

<h3>Whittier's current memorials</h3>

<p>
  A you know, there are a number of memorials to John Greenleaf Whittier in the city and vicinity,
  for example, the Whittier Birthplace on 305 Whittier Road, the Whittier Home in Amesbury, and a
  Whittier Building, a Whittier Bridge, and two Whittier Schools. We think that a downtown statue of
  Haverhill's favorite son would complement these tributes. Two reasons come readily to mind.
</p>

<h3>Reason 1 for Whittier downtown: to enhance the daily lives of citizens</h3>

<p>
  The first reason is to have Whittier's values and accomplishments displayed to Haverhill citizens,
  young and old, as they go about their daily activities. These values and accomplishments enabled
  Whittier to become a major poet, abolitionist, and advisor during his time, and they will serve,
  we believe, as a daily inspiration to the citizens of Haverhill. The list of Whittier's virtues is
  long, and it includes honesty, humility, courage, perseverance, righteousness, and self-reliance.
  This is why his contemporaries elected him to the Massachusetts House of Representatives and
  elicited his aid in the founding of the national Republican Party; and why Harvard invited him to
  serve two terms as an overseer and awarded him an honorary Doctor of Laws degree. It is why
  schools and cities in the nation, and one college, are named after him; and why, on his 80<sup
    >th</sup
  > birthday, he received a birthday letter signed by 59 U.S. senators, every member of the U.S. Supreme
  Court, and 330 members of the U.S. House of Representatives. Finally, it is why, after his death in
  1892, major newspapers, including The New York Times, The Washington Post, The San Francisco Chronicle,
  The Cleveland Plain Dealer, and the Philadelphia Inquirer, published obituaries and notices. He is a
  worthy model for living.
</p>

<h3>Reason 2 for Whittier downtown: to enhance the stature of the city of Haverhill</h3>

<p>
  The second reason for a downtown statue is to place Whittier <em>within</em> the city he loved in order
  to accentuate their association. Other communities have seen the value of doing this. For example, there
  is a hometown statue of Longfellow in Portland, Maine; one of Poe in Baltimore; one of Whitman in Brooklyn;
  one of Thoreau at Walden Pond; two of Mark Twain in Hannibal, Missouri; and one of Whittier's partner
  in abolition, William Lloyd Garrison, in Newburyport. The only statue of Whittier is in Whittier, California.
  Haverhill is fortunate indeed to be the birthplace of this extraordinary American, and the city cannot
  but gain in stature in the eyes of both citizens and outsiders by being even more closely associated
  with him.
</p>

<h3>Work completed and proposed next steps</h3>

<p>
  The Committee has been meeting for more than a year. Most recently, we have been been making the
  rounds of interested parties, including the Mayor's Office, Sal Lupoli Companies, and the
  &ldquo;Possible Dreams&rdquo; annual forum, describing our project and eliciting feedback. We have
  also consulted with sculptors. The feedback has been uniformly positive. If the Haverhill City
  Council also has a positive opinion of the project, we intend to continue community outreach and
  begin steps toward the formation of a private fundraising campaign.
</p>

