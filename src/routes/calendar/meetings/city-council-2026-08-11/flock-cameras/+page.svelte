</p>

<p>
  Councilor Sullivan asked whether there had been any instances of misuse of the Flock system by a
  Haverhill police officer, and Deputy Chief Pare stated there had not. Councilor McGonagle stated
  he is in support and would like to give the Police Department every tool that is not overbearing.
  President Jordan asked about data retention, and Deputy Chief Pare stated that information is
  retained for 30 days, while the audit trail is permanent. She also stated that the system is not
  shared with federal agencies or ICE. Vice President Michitson asked about data downloaded before
  the 30-day deletion period, and Deputy Chief Pare stated that it would be handled under the
  department&rsquo;s evidence policy.
</p>

<p>
  Motion by Councilor Lewandowski to send a letter to the City Solicitor to work with the Police to
  establish an ordinance to include guardrails for the use of Flock. Second Vice President Michitson<br
  />
  PASSED &ndash; Yeas 11, Nays 0, Absent 0
</p>

<p>
  Motion by Councilor Ferreira to send Flock cameras to Public Safety committee for further
  discussion and recommendation back to council. Second by Vice President Michitson.<br />
  PASSED &ndash; Yeas 10, Nays 1 (Lewandowski), Absent 0
</p>

<p>
  Elizabeth Hamel (25 Albert Avenue) stated that she is not opposed to Flock cameras but questioned
  the cost to the City. Deputy Chief Pare stated that the five-year contract totals $137,000 and
  explained that, like all technology tools, Flock is an expense. Hamel also asked why cameras that
  are not working are not being updated. Deputy Chief Pare stated that the cameras operate 24/7 and
  that the Police Department submits a service ticket whenever an issue occurs.
</p>

<p>
  Dale Leone (21 Race Street) raised concerns about Flock&rsquo;s nationwide data-sharing practices,
  law enforcement access, and whether local information could ultimately be accessed by agencies
  such as ICE through intermunicipal sharing. He also questioned whether cameras could be
  reactivated without community approval. Trevor Chandler stated that there is no default statewide
  or nationwide sharing, no &ldquo;daisy-chain&rdquo; access, and that individual agencies control
  and audit their own sharing settings. He acknowledged that communication issues with maintenance
  teams could result in a camera being inadvertently reactivated.
</p>

<p>
  Sven Amirian (45 Talmuth Avenue) expressed concern that Flock cameras could create a broad
  surveillance network by collecting and sharing vehicle and license plate information from
  individuals who have not committed crimes. He called for greater transparency and public oversight
  regarding data retention, access, and sharing, particularly with federal agencies, and asked the
  Council to review the City&rsquo;s contract, including termination and early-exit provisions.
</p>

<p>
  Andrew Ryan (33 Summit Avenue) stated that his concerns were not with the cameras themselves but
  with Flock&rsquo;s history of privacy concerns and potential misuse and sharing of data. He cited
  incidents involving improper surveillance and data sharing and urged the City to address these
  concerns transparently, involve affected residents, and provide opportunities for public input.
  Trevor Chandler stated that a communication issue with the Littleton Police Chief resulted in
  cameras being turned back on but emphasized that there was no malicious intent.
</p>

<p>
  Leah Allen (122 Rosemont Street) raised concerns about privacy, the City&rsquo;s five-year
  contract price, and whether Flock could use residents&rsquo; data. She referenced ACLU research
  regarding changes to Flock&rsquo;s terms, including provisions concerning continued use and
  potential sharing of customer data. Trevor Chandler stated that Flock does not sell data and
  explained that perpetual language in the contract is intended only to allow anonymized data to
  remain available as a reference for improving machine-learning accuracy, not for resale or
  unrestricted use. He also discussed Flock&rsquo;s role in providing affordable public safety
  technology and increasing competition among vendors.
</p>

<p>
  Corey O&rsquo;Neill (Haverhill resident) urged the City Council to pause its Flock contract until
  Councilors have a full understanding of the system&rsquo;s artificial intelligence capabilities,
  data retention, tracking, and privacy implications. He stated that searchable surveillance of
  individuals&rsquo; movements is fundamentally different from ordinary public observation and
  expressed concern about collecting information on people who are not suspected of wrongdoing.
</p>

