<h2>Minutes</h2>

<p>
  Acting Deputy Police Chief Meaghan Pare addressed the Council regarding the Haverhill Police
  Department&rsquo;s use of Flock Safety technology as an investigative tool. She explained that the
  system assists officers in solving crimes, locating vehicles, and developing investigative leads,
  but does not replace traditional police work or establish probable causes. The system captures
  vehicle and license plate information from designated public cameras and does not use facial
  recognition or collect demographic information. Access is limited to trained and authorized
  personnel, with searches logged and subject to audit. Routine data is retained for 30 days unless
  preserved as evidence, and data sharing with other agencies requires Haverhill&rsquo;s
  authorization. Deputy Chief Pare stated the department currently has 19 Flock cameras, which have
  been in use since 2023.
</p>

<p>
  Trevor Chandler of Flock Safety addressed the Council and clarified that Flock does not sell
  customer data and that the city owns its data. He explained that Haverhill controls data-sharing
  agreements and highlighted the technology&rsquo;s use in investigations, including missing-person
  cases. Vice President Michitson asked about cybersecurity, access controls, data ownership,
  privacy, and the guardrails governing use of the system. Trevor Chandler discussed Flock&rsquo;s
  security measures, including encryption, CJIS compliance, NIST certification, and SOC 2 Type II
  compliance. Deputy Chief Pare explained that data sharing with other agencies is not automatic and
  requires Haverhill&rsquo;s authorization through an agreement or MOU, with access limited to
  designated cameras.
</p>

<p>
  Council members discussed the balance between public safety and residents&rsquo; privacy and the
  need for clear policies and oversight. Vice President Michitson stated that he supports the use of
  Flock but believes the City should ensure appropriate guardrails are in place and consider
  adopting a policy or ordinance governing its use. Councilor Basiliere noted the potential public
  safety benefits, including assisting with missing-person and human trafficking investigations.
  Councilor Lewandowski asked how many cameras are in use and how long the system has been in place.
  Deputy Chief Pare confirmed there are 19 cameras and that the system has been used since 2023.
  Councilor Lewandowski noted that the city currently does not have an ordinance governing Flock
  technology.
</p>

<p>
  <strong>
    Motion by Councilor Lewandowski to send this to our City Solicitor to work with the Police to
    establish some type of ordinance relative to the concerns regarding prohibited uses, access,
    data retention, etc. Second Vice President Michitson
  </strong>
</p>

<p>
  Councilor Lewandowski supported Flock as a crime-solving tool while stressing privacy, access
  controls, search audits, and safeguards against improper or biased searches. She suggested
  creating a webpage with information and a complaint mechanism for residents. Trevor Chandler noted
  that Flock recently introduced an Audit Assistant tool. Councilor Ferreira opposed Flock cameras,
  citing privacy, surveillance, data aggregation, and transparency concerns, and supported exploring
  alternative public safety tools. She would recommend this going to a subcommittee for further
  review.
</p>

<p>
  <strong>
    Motion by Councilor Ferreira to send to Public Safety committee further discussion and
    recommendation back to council. Second by Vice President Michitson.
  </strong>
</p>

<p>
  Councilor Rogers asked whether the 19 cameras included in the five-year contract represented the
  maximum number of cameras and whether additional cameras could be added automatically. Deputy
  Chief Pare clarified that any additional cameras would require authorization and payment by the
  City and would need to come to the city for approval.
</p>

