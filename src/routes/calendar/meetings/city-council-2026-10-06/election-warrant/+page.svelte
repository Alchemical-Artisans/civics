  Do you approve of a law summarized below, on which no vote was taken by the Senate or the House of
  Representatives before May 6, 2026?
</p>

<h3>SUMMARY</h3>

<p>
  This proposed law would make most records held by the Legislature and the Office of the Governor
  public records under the Massachusetts Public Records Law. This proposed law would exempt
  documents related to the development of public policy and communications between legislators and
