  certification of the petition, the City must place the question on the ballot for the next
  regularly occurring municipal or state election in the form prescribed by the statute. The above
  question, if voted in the affirmative, would allow consumption of marijuana and marijuana products
  on the premises where sold, subject to the reasonable limitations established by the City.
</p>

