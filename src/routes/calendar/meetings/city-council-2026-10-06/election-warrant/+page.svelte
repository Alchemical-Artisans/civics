<h2>QUESTION 3: LAW PROPOSED BY INITIATIVE PETITION</h2>

<p>
  Do you approve of a law summarized below, on which no vote was taken by the Senate or the House of
  Representatives before May 6, 2026?
</p>

<h3>SUMMARY</h3>

<p>
  This proposed law would eliminate political party primaries for state elections and instead
  establish a system where there would be a single, all-party primary in which all candidates,
  regardless of their party affiliation, would be listed on one ballot, and voters could vote for
  any candidate on the ballot. The two candidates receiving the most votes in the primary would
  advance to the general election ballot.
</p>

<p>
  This proposed law would require candidates for governor and lieutenant governor to run and be
  listed jointly on the ballot in the primary.
</p>

<p>
  This proposed law would provide political party status to any group whose candidates for any
  statewide office received at least 3% of the ballots cast in the state primary.
</p>

<p>
  <em><strong>A YES VOTE</strong></em> would eliminate separate party primaries for state elections and
  require a single primary in which all candidates appear on one ballot, voters could vote for any candidate,
  and the top two candidates would advance to the general election.
</p>

<p>
  <em><strong>A NO VOTE</strong></em> would make no change to the laws governing primary elections.
</p>

<h2>QUESTION 4: LAW PROPOSED BY INITIATIVE PETITION</h2>

<p>
  Do you approve of a law summarized below, on which no vote was taken by the Senate or the House of
  Representatives before May 6, 2026?
</p>

<h3>SUMMARY</h3>

<p>
  This proposed law would permit eligible individuals to register to vote or update their voter
  registration address on Election Day.
</p>

<p>
  An individual who is eligible to vote could register to vote on Election Day by going to the
  polling place in the precinct where they live during voting hours and presenting proof of
  residency and signing a written oath. Proof of residency could be a valid photo identification, or
  documentation showing the individual&rsquo;s name and the address where the individual resides,
  such as a current utility bill, bank statement, government check, residential lease, wireless
  telephone statement, paycheck, current student fee statement or other document from a
  post-secondary school, or another government document or correspondence. The written oath would
  require the individual to certify that they are a citizen of the United States, are at least 18
  years old, are not legally prohibited from voting, and have not and will not vote in the same
  election at another location. The oath would require the individual to acknowledge that providing
  false information is a felony punishable by not more than 5 years imprisonment or a fine of not
  more than $10,000, or both.
</p>

<p>
  If an individual did not present proof of residency, they would be allowed to cast a provisional
  ballot, which would be counted only if the individual returned to provide the required information
  before the close of polls for a municipal election; within two days after a state primary; or
  within six days after a state election.
</p>

<p>
  Individuals who register to vote on Election Day would be registered to vote in future elections
  as well as in the election taking place that day.
</p>

<p>
  Individuals who are already registered to vote would not be able to change their political party
  affiliation on Election Day.
</p>

<p>The proposed law would take effect on January 1, 2028.</p>

<p>
  <em><strong>A YES VOTE</strong></em> would permit eligible citizens to register to vote or to update
  their voter registration address at their polling place on Election Day.
</p>

<p>
  <em><strong>A NO VOTE</strong></em> would make no change to the laws governing voter registration.
</p>

<h2>QUESTION 5: LAW PROPOSED BY INITIATIVE PETITION</h2>

<p>
  Do you approve of a law summarized below, on which no vote was taken by the Senate or the House of
  Representatives before May 6, 2026?
</p>

<h3>SUMMARY</h3>

<p>
  This proposed law would change the limit on how much revenue the state can collect in a given
  year. The proposal would limit state revenue in a given year to the net amount of state revenue
  from the year before, increased by a rate equal to the average growth of wages and salaries in
  Massachusetts over the most recent three years. If revenue collected by the state in a given year
  exceeds the limit, the excess amount would be refunded to taxpayers the following year. The
  proposed law would include all revenue from the surtax on incomes over $1 million when calculating
  the revenue limit and when determining whether state revenue exceeds the limit.
</p>

<p>The provisions of the proposed law would all be effective as of July 1, 2027.</p>

<p>
  The proposed law states that, if any of its parts were declared invalid, the other parts would
  stay in effect.
</p>

<p>
  <em><strong>A YES VOTE</strong></em> would change the limit on state revenue collection, tying it to
  prior year collections plus average wage and salary growth, and provide for a rebate of revenue exceeding
  that limit.
</p>

<p>
  <em><strong>A NO VOTE</strong></em> would make no change in the law relative to state revenue collection.
</p>

<h2>QUESTION 6: LAW PROPOSED BY INITIATIVE PETITION</h2>

<p>
  Do you approve of a law summarized below, on which no vote was taken by the Senate or the House of
  Representatives before May 6, 2026?
</p>

<h3>SUMMARY</h3>

<p>
  This proposed law would establish a Nature for All Fund that, subject to appropriation by the
  Legislature, would receive 50% of state taxes collected from the sale and use of sporting goods,
  recreational vehicles, and golf courses for the first year of its operation. After July 1, 2028,
  the Nature for All Fund would begin receiving, subject to appropriation by the Legislature, 100%
  of state taxes collected on the sale and use of sporting goods, recreational vehicles, and golf
  courses. The sales tax revenue received by the Nature for All Fund would exclude sales tax revenue
  transferred to the Massachusetts Bay Transportation Authority State and Local Contribution Fund
  and the School Modernization and Reconstruction Trust Fund. The proposed law would allow the state
  Executive Office of Energy and Environmental Affairs to spend the money in the Nature for All Fund
  for natural resource conservation.
</p>

<p>
  The proposed law would allow public and private donations to the Nature for All Fund. The proposed
  law would prevent the state comptroller from transferring surplus funds in the Nature for All Fund
  at the end of the fiscal year. It would also allow state agencies, municipalities, public
  charities involved in natural resource conservation, tribal governments, and other regional public
  entities to receive money from the Nature for All Fund.
</p>

<p>
  Natural resource conservation would include the conservation or restoration of land to protect
  drinking water, streams, rivers, lakes, coasts, farms, forests, connectivity between open spaces,
  and lands and natural resources of indigenous cultural significance. Natural resource conservation
  would also include the creation, improvement, and management of parks, trails, greenspaces or
  outdoor recreation access.
</p>

<p>
  The proposed law would establish a 15-member Nature for All Board that consists of five state
  officials and ten members of the public appointed by the Governor. The proposed law would require
  the ten members of the public to include representatives of underserved communities and indigenous
  peoples and at least one person with expertise or experience in natural resource conservation. The
  proposed law would allow the state Executive Office of Energy and Environmental Affairs to spend
  money from the Nature for All Fund to hire staff to manage the fund. The proposed law would also
  require the Nature for All Board to establish rules about how the money in the Nature for All Fund
  should be spent, including rules regarding alignment with environmental justice principles, access
  to and restoration of lands and natural resources of indigenous cultural significance, promotion
  of affordable housing development, and other matters regarding spending and bond issuance.
</p>

<p>
  The proposed law would require the state Executive Office of Energy and Environmental Affairs to
  submit an annual report to various state committees regarding the funds spent to buy or improve
  land in cities and towns containing environmental justice populations.
</p>

<p>The proposed law would take effect on July 1, 2027.</p>

<p>
  <em><strong>A YES VOTE</strong></em> would create a fund that could be utilized for natural resource
  conservation that would receive some state taxes collected on the sale and use of sporting goods and
  recreational vehicles, and the use of golf courses.
</p>

<p>
  <em><strong>A NO VOTE</strong></em> would not create this natural resource conservation fund or change
  how sales and use taxes are spent.
</p>

<h2>QUESTION 7: LAW PROPOSED BY INITIATIVE PETITION</h2>

<p>
  Do you approve of a law summarized below, on which no vote was taken by the Senate or the House of
  Representatives before May 6, 2026?
</p>

<h3>SUMMARY</h3>

<p>
  This proposed law would allow single-family homes to be built in a residentially zoned area as
  long as the land on which it is to be constructed is at least 5,000 square feet, has at least 50
  feet of land bordering the street, road, or public way that it faces, and has access to public
  sewer and water services.
</p>

<p>
  The proposed law would allow cities and towns to reasonably regulate certain aspects of those
  single-family homes, including their height, distance from neighboring buildings, open space,
  parking requirements, and whether they can be rented out on a short-term basis. The proposed law
  would also allow the Executive Office of Housing and Livable Communities to issue guidance or
  regulations to administer the proposed law.
</p>

<p>
  <em><strong>A YES VOTE</strong></em> would allow single-family homes to be built on lots of 5,000 square
  feet or more in residential areas, subject to reasonable local regulation of certain aspects of those
  homes.
</p>

<p>
  <em><strong>A NO VOTE</strong></em> would make no change to the law relative to building single-family
  homes.
</p>

<h2>QUESTION 8: LAW PROPOSED BY INITIATIVE PETITION</h2>

<p>
  Do you approve of a law summarized below, on which no vote was taken by the Senate or the House of
  Representatives before May 6, 2026?
</p>

<h3>SUMMARY</h3>

<p>
  The proposed law would change the type and amount of marijuana that may legally be possessed in
  Massachusetts by repealing the laws that legalize, regulate, and tax the retail sale of adult
  recreational use marijuana in Massachusetts. The proposed law would also permit persons 21 years
  of age and older to possess 1 ounce or less of marijuana including no more than 5 grams in the
  form of concentrate, and to gift or transfer to another person 21 years of age and older 1 ounce
  or less of marijuana including no more than 5 grams in the form of concentrate. The proposed law
  would also impose a civil penalty of $100 and forfeiture of the marijuana for the possession of
  marijuana between the weight of 1 and 2 ounces.
</p>

<p>
  For persons 21 years of age and younger, the proposed law would make the possession of 2 ounces or
  less of marijuana a civil infraction subject to a $100 fine, forfeiture of the marijuana,
  completion of a drug awareness program and community service, and notification to their parents or
  legal guardian of the offense and penalties.
</p>

<p>
  The proposed law would allow currently licensed adult recreational marijuana businesses to apply
  on an expedited basis to become a licensed medical marijuana dispensary and to sell their
  remaining inventory of adult recreational marijuana to medical marijuana dispensaries. The
  proposed law would retain the Cannabis Control Commission but modify its authority so it would
  regulate only the medical marijuana market.
</p>

<p>
  The proposed law states that, if any of its parts were declared invalid, the other parts would
  stay in effect.
</p>

<p>The proposed law would take effect on January 1, 2028.</p>

<p>
  <em><strong>A YES VOTE</strong></em> would prohibit the legalization, regulation, and taxation of the
  retail sale of adult recreational use marijuana, and change the penalties for possession of marijuana.
</p>

<p><em><strong>A NO VOTE</strong></em> would make no change to the law relative to marijuana.</p>

<h2>QUESTION 9: REFERENDUM ON AN EXISTING LAW</h2>

<p>
  Do you approve of a law summarized below, which was approved by the House of Representatives on
  July 18, 2024 by a vote of 124 to 33, and approved by the Senate on July 18, 2024 by a vote of 35
  to 5?
</p>

<h3>SUMMARY</h3>

<p>This law makes a number of changes to Massachusetts laws governing firearms.</p>

<p>
  The law adds school administrators and licensed healthcare providers as parties permitted to ask a
  court to issue an Extreme Risk Protection Order &ndash; requiring an individual to surrender or
  relinquish their firearm licenses, permits, and firearms - if an individual is a present danger to
  self or others. The law also provides that, when issuing an Harassment Prevention Order, a court
  may also order the surrender of firearms licenses, permits, and firearms.
</p>

<p>
  The law imposes penalties for possessing, creating, and transferring untraceable &ldquo;ghost
  gun&rdquo; firearms and requires all firearms except antiques and relics, including unfinished
  frames and receivers that can be readily made into a finished product, to have serial numbers. The
  law includes privately-made guns like 3D-printed guns within the provisions governing untraceable
  &ldquo;ghost gun&rdquo; firearms.
</p>

<p>
  The law changes firearms licensing requirements to: (1) allow local licensing authorities to
  request prior license and permit information from the state, as well as access petitions for
  involuntary mental health commitments denied by a court in addition to prior involuntary
  commitments, as a part of their review of applications for licenses to carry firearms, firearm ID
  cards, and licenses to sell firearms; (2) require an individual to be 21 years of age to own
  semiautomatic rifles or shotguns; (3) add the possibility of incarceration of up to six months for
  a second offense of failing to report a firearm loss or theft; and (4) enable 12-15 year olds to
  apply for a self-defense spray permit with parental permission, and 15 to 18 year olds to apply
  independently.
</p>

<p>
  The law allows local firearm licensing authorities to transfer the responsibility to inspect
  firearm dealers to the State Police. The law requires local licensing authorities to attend
  statewide training regarding those inspections. It requires dealers to confiscate expired or
  suspended licenses and report them to the state and to local licensing authorities.
</p>

<p>
  The law changes the definition of &ldquo;machine gun&rdquo; to include bump stocks, trigger
  cranks, Glock switches and auto sears among the devices whose possession and use are subject to
  penalties. It expands the definition of &ldquo;silencer&rdquo; to include the parts used to
  construct a silencer.
</p>

<p>
  The law clarifies how to determine whether a firearm is an assault-style weapon and the
  circumstances under which a person may continue to possess assault-style weapons and large
  capacity feeding devices they already own.
</p>

<p>
  The law requires the state Firearm Control Advisory Board and the state Secretary of Public Safety
  and Security to review and update the rosters of prohibited assault-style firearms, approved
  firearms, and approved firearms sold for target shooting.
</p>

<p>
  The law clarifies requirements relating to the carry and transport of firearms in motor vehicles
  and ATVs. It prohibits the carrying of firearms in government buildings, polling locations, and
  schools, with certain exceptions.
</p>

<p>
  The law expands data compilation and reporting requirements to and from the state, and creates a
  publicly-accessible dashboard of anonymized aggregate firearm data, along with a commission to
  study that data.
</p>

<p>
  The law requires the State Police to provide training and a test for new applicants for licenses
  to carry or Firearm ID cards.
</p>

<p>
  The law establishes two special legislative commissions &ndash; one to examine funding for
  violence prevention services, and one to study emerging firearms technology.
</p>

<p>The law criminalizes discharging a firearm and striking a building in use.</p>

<p>
  <em><strong>A YES VOTE</strong></em> would keep in place the law, which increases the regulation of
  firearms, including ghost guns, machine guns, and assault-style weapons.
</p>

<p><em><strong>A NO VOTE</strong></em> would repeal this law.</p>

