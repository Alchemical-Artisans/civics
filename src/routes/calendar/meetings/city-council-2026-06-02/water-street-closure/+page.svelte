<h2>Minutes</h2>

<p>
  Councilor Melissa Lewandowski raised concerns about increased traffic and safety issues on
  Shapleigh Street following the May 6 partial house collapse on Water Street, which required a
  temporary detour through the neighborhood. Lt. Kevin Lynch explained that the detour was moved
  back to Boardman Street because it is wider and better suited for truck traffic, noting that many
  truck drivers follow GPS directions despite posted signage. Mayor Barrett reported that the City
  is working with the property owner and insurance representatives to secure the damaged building as
  quickly as possible, while acknowledging the impact on displaced residents. Resident Bruce Baxter
  (5 Shapleigh Avenue) thanked Councilor Lewandowski, the Mayor&rsquo;s Office, and the Police
  Department for responding to neighborhood concerns and implementing changes that provided
  immediate relief.
</p>

