<h2>Minutes</h2>

<p>
  Mayor Barrett addressed the council. She noted this is a roof replacement and approximately 76% of
  the cost will be reimbursed through the grant, substantially reducing the expense.
</p>

<p>
  Councilor Rogers noted that the project cost had increased to approximately $3.5 million, plus an
  additional $300,000 for the schools, bringing the total to nearly $4 million. Mayor Barrett
  clarified that the City would not be paying the full $4 million. Councilor Rogers responded that
  taxpayer dollars would ultimately fund the project, to which Mayor Barrett agreed, adding that the
  funds would not come solely from Haverhill taxpayers. Councilor Rogers questioned whether the City
  was required to proceed through the current process and whether obtaining a direct quote might
  result in a lower cost. Mayor Barrett explained that if the City funded the project independently,
  the cost would likely be around $4 million, whereas the current process allows for a 75 percent
  reimbursement. Clancy Main of the School Department addressed the Council and stated that, after
  reimbursement from the Massachusetts School Building Authority (MSBA), the City&rsquo;s share of
  the project would range from approximately $661,000 in the best-case scenario to $815,000 in the
  worst-case scenario. He explained that the project had undergone the required due diligence and
  schematic design phases and that professional estimators had reviewed and priced the project to
  ensure the costs were reasonable and accurate.
</p>

