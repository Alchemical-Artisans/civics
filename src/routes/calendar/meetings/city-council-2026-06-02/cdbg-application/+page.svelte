<h2>Minutes</h2>

<p>
  Andrew Herlihy addressed the council. He noted the city will receive $940,208 in the community
  block grant. That equals a 2.44% increase over last year. The city has received the CDBG funds for
  52 years, totaling about $59 million. The council&rsquo;s approval is needed for the mayor to
  submit the annual grant plan and budget. The federal rules limit spending on administration and
  non-profit grants that serve low-moderate income residents. He also noted the proposed CDBG budget
  will continue to prioritize housing rehabilitation, neighborhood improvements and support low and
  moderate income residents. Funds will also support economic development initiatives and address
  unsafe vacant properties. He stated the city will begin the required public comment process.
</p>

