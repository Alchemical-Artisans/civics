<p>
  <strong>8.3.</strong> The <em>Haverhill License Commission</em> has voted to adopt an additional class
  of liquor license and submits the appropriate Order
</p>

<blockquote>
  <p>
    <strong>8.3.1.</strong> Order &ndash; That the City of Haverhill hereby accepts the following provisions
    of G.L. Chapter Section 12, relative to the sale of liqueurs and cordials by those licensed to sell
    wines and malt beverages:
  </p>
  <p>
    &ldquo; In any city or town which votes to accept the provisions of this paragraph, a common
    victualler, who holds a license under this section to sell wines and malt beverages may, upon
    written approval, also sell liqueurs and cordials pursuant to said license, subject, however, to
    all other licensing provisions of this chapter.&rdquo;
  </p>
</blockquote>
