  Governor and the Legislature to add a seat to the MSBA board specifically for a representative
  with vocational/technical experience.
</p>

<h3>
  RESOLUTION 4: REGARDING CLARIFICATION OF SECLUSION STANDARDS WITHIN EMERGENCY BEHAVIORAL RESPONSE
  PROCEDURES (603 CMR 46.00)
</h3>

<p><em>(Submitted by the Hampden-Wilbraham Regional School Committee)</em></p>

<p>
  WHEREAS Massachusetts public schools are committed to fostering safe, supportive, and inclusive
  learning environments in which preventive, proactive, and trauma-informed behavioral supports are
  the foundation of student success; and
</p>

<p>
  WHEREAS school districts prioritize the use of preventive strategies, including de-escalation
  techniques, co-regulation supports, sensory and environmental accommodations, and other positive
  behavioral interventions designed to support students before behavior reaches a crisis level; and
</p>

<p>
  WHEREAS despite the effective use of preventive and supportive interventions, there are rare
  circumstances in which a student may experience acute dysregulation and may present an imminent
  risk of serious physical harm to self or others, requiring immediate emergency response; and
</p>

<p>
  WHEREAS 603 CMR 46.00 permits emergency interventions such as time-out, seclusion, and physical
  restraint only as a last resort in such limited circumstances, and requires that all less
  restrictive alternatives be attempted or deemed inappropriate based on the situation; and
</p>

<p>
  WHEREAS clear understanding and consistent application of the definition of emergency
  seclusion&mdash;specifically involuntary confinement of a student alone in a room or area from
  which they are physically prevented from leaving&mdash;is essential to ensuring student safety,
  regulatory compliance, and protection of civil rights; and
</p>

<p>
  WHEREAS districts would benefit from further clarity distinguishing emergency seclusion from
  supportive, supervised, and voluntary or staff-guided time-out practices used to assist students
  in regaining emotional regulation and returning to learning; and
</p>

<p>
  WHEREAS the amended regulations regarding Physical Restraint, Timeout, and Emergency Seclusion
  become effective August 17, 2026 and as of June 1st, 2026, the Massachusetts Department of
  Elementary and Secondary Education (DESE) has provided no training to districts; and
</p>

<p>
  WHEREAS the amended regulations do not offer the clarity required for successful implementation;
</p>

<p>
  THEREFORE, BE IT RESOLVED that the Massachusetts Association of School Committees urges DESE to
  provide additional clear guidance reinforcing the nuanced differences between time-out and
  emergency seclusion and in the Department&rsquo;s viewpoint types of situations/scenarios that
  would warrant both; and
</p>

<p>
  BE IT FURTHER RESOLVED that MASC supports DESE in further clarifying the distinction between
  time-out, and emergency seclusion, including the use of practical, real-life examples and
  decision-making tools for school personnel; and
</p>

<p>
  BE IT FURTHER RESOLVED that MASC encourage ongoing in-person statewide training and professional
  development to ensure staff are equipped to implement preventive strategies effectively and to
  respond appropriately when those strategies are not sufficient to prevent escalation; and
</p>

<p>
  BE IT FURTHER RESOLVED that the Department make available entitlement grants for Local Education
  Agencies (LEAs) that provide financial support to provide ongoing professional development to
  faculty, staff, and families in preventative behavior regulation strategies that include
  de-escalation, trauma informed practices, as well as appropriate reactive strategies for when
  students engage in activities that present an imminent risk of serious physical harm to self or
  others; and
</p>

<p>
  BE IT FINALLY RESOLVED that MASC reaffirm its commitment to student dignity, safety, and access to
  education, and support policies that ensure emergency interventions are rare, clearly defined,
  consistently applied, and always secondary to preventive and supportive behavioral practices.
</p>

<h3>
  RESOLUTION 5: ALLOWING REGIONAL SCHOOL COMMITTEES TO ACCESS SPECIAL EDUCATION RESERVE FUNDS BY A
  MAJORITY VOTE OF THE SCHOOL COMMITTEE
</h3>

<p><em>(Submitted by the Nashoba Valley Technical School Committee)</em></p>

<p>
  WHEREAS Special Education Reserve Funds can help districts defray the costs of extraordinary or
  unexpected special education costs; and
</p>

<p>WHEREAS Special Education costs have increased exponentially in recent years; and</p>

<p>WHEREAS Circuit Breaker reimbursement lags behind typical budget processes; and</p>

<p>WHEREAS school committees are the municipal legislature of the school district; and</p>

<p>
  WHEREAS Massachusetts General Laws currently require that districts seek approval from both the
  select board/city council and the school committee to access the funds; and
</p>

<p>
  WHEREAS this puts an undue burden on multi-member districts that may have to seek approval from up
  to eight separate municipalities;
</p>

<p>
  THEREFORE BE IT RESOLVED that the Massachusetts Association of School Committees calls upon the
  Governor and the Legislature to approve the proposed budgetary amendment allowing districts to
  seek approval from the school committee only.
</p>

<h3>REAUTHORIZATION OF PREVIOUSLY APPROVED RESOLUTIONS</h3>

<p>
  The 2023 Delegate Assembly approved an amendment to the By-Laws that resolutions will expire at
  the conclusion of the Delegate Assembly three years after their adoption. Expiring resolutions may
  be reconsidered and readopted by the delegates at the annual meeting at which the resolutions
  would expire. The rationale for the amendment was that it:
</p>

<ul>
  <li>Permits three years of focus on resolutions which overlaps with two legislative cycles.</li>
  <li>
    Provides an additional opportunity for school committees to be involved in the resolution
    process by championing resolutions that are set to expire.
  </li>
  <li>
    Allows the Association to affirm what&rsquo;s important to the current membership by
    re-adoption.
  </li>
  <li>Clears expired, less relevant, or no longer supported resolutions for new priorities.</li>
</ul>

<p>
  Following are the three resolutions set to expire this November unless reauthorized by a vote of
  the Delegate Assembly.
</p>

<ul>
  <li>Regarding Investigations and Recommendations for Transportation Bidding Procedures</li>
  <li>Full, Stable Funding for METCO</li>
  <li>Massachusetts School Building Authority Assistance Programs</li>
</ul>

<h3>REGARDING INVESTIGATIONS AND RECOMMENDATIONS FOR TRANSPORTATION BIDDING PROCEDURES</h3>

<p>
  <em
    >(Originally sponsored by the Southeastern Regional Vocational Technical School Committee;
    Submitted for reauthorization in 2026 by the Mendon-Upton Regional School Committee)</em
  >
</p>

<p>
  WHEREAS school districts across the commonwealth are struggling with the problem of transportation
  services and the bidding and purchasing of these services; and
</p>

<p>
  WHEREAS a stunning number of districts find that, after soliciting multiple bids, it is a frequent
  occurrence that only a single bidder submits a proposal; and
</p>

<p>
  WHEREAS in light of the paucity of submissions, the single bidder is able to propose significant
  increases over previous years exacerbating not only financial matters, but also skepticism about
  the integrity of the bidding process.
</p>

<p>
  THEREFORE BE IT RESOLVED that the MA Association of School Committees prevail upon the Office of
  the State Auditor to investigate the bidding practices of school transportation providers, and to
  present such findings and recommendations as may be necessary to contain costs and make more
  efficient transportation services available for public schools.
</p>

<p>MASC status update on this resolution:</p>

<p>
  MASC successfully lobbied the legislatre, via an FY25 Supplemental Budget, to direct the Office of
  the Inspector General to produce a Special Education Transportation Study. The findings of that
  study were published in February 2026. Among the findings are: (1) Massachusetts is an outlier in
  its use of a reimbursement model to fund student transportation, which puts significant
  administrative and financial burdens on local districts; (2) Vendors are not required to provide
  school districts with detailed invoices, making it impossible for districts to understand what
  they are paying for; and (3) There is no central repository for school transportation bids and
  contracts, depriving districts of helpful information when procuring these services. The report
  makes recommendations to address these issues and others. It also makes note that school
  transportation costs have been studied at least four times in the last 20 years with varying
  levels of success on follow-through of those studies&rsquo; recommendations.
</p>

<h3>FULL, STABLE FUNDING FOR METCO</h3>

<p><em>(Originally sponsored by the Arlington School Committee)</em></p>

<p>
  WHEREAS in 1966 the first 220 students rode buses from Boston neighborhoods to schools in seven
  suburbs; and
</p>

<p>
  WHEREAS in 1968 the Massachusetts Legislature passed the Racial Imbalance Act, in which the
  Commonwealth accepted financial responsibility &ldquo;for any town that wishes to enroll students
  from outside the district for the purpose of racial integration (subject to appropriation); and
</p>

<p>
  WHEREAS in 1968 the Metropolitan Council for Educational Opportunity (METCO) assumed
  responsibility for implementing the provisions of the Racial Imbalance Act, providing support for
  students, families, and receiving districts; and
</p>

<p>
  WHEREAS METCO&rsquo;s mission is to provide students with a strong academic foundation rich in
  cultural, educational, ethnic, socioeconomic, and racial diversity and foster the opportunity for
  children from Boston and from neighboring suburbs to develop a deeper understanding of each other
  in an integrated public school setting; and
</p>

<p>
  WHEREAS over the last half century, METCO has reached tens of thousands of students, supporting
  3,100 families annually in 31 participating suburban school districts and 190 public schools, with
  graduation rates and college attainment far above state averages; and
</p>

<p>
  WHEREAS METCO creates environments where students, parents and teachers of different backgrounds
  can appreciate diversity, find common ground through shared experiences, build lifelong
  inter-racial friendships, and strive toward the mutual goal of preparing young people to become
  global citizens; and
</p>

<p>
  WHEREAS METCO districts have expressed an interest in welcoming more METCO students into their
  schools; and
</p>

<p>
  WHEREAS METCO has been recognized as the nation&rsquo;s most successful school integration program
  in the United States; and
</p>

<p>
  WHEREAS requiring METCO funding to be subject to appropriation results in METCO families and
  partner districts spending considerable time and energy to lobby for funding to maintain the
  current level of services;
</p>

<p>
  THEREFORE BE IT RESOLVED that the Massachusetts Association of School Committees calls upon the
  Governor and the Legislature to create a stable funding structure to support METCO and its partner
  districts that fully funds the support provided by METCO, and the cost of providing services
  delivered by METCO&rsquo;s partner districts.
</p>

<p>MASC status update on this resolution:</p>

<p>
  MASC has repeatedly made it known to the Governor and Legislature that METCO deserves a stable
  funding structure. Similarly, we have supported METCO&rsquo;s advocacy efforts for funding in the
  annual budget via line item 7010-0012. In the FY26 Budget we joined them in their effort to be
  fully funded at $33 million.
</p>

<h3>MA SCHOOL BUILDING AUTHORITY ASSISTANCE PROGRAMS</h3>

<p><em>(Originally submitted by the Wachusett Regional School Committee)</em></p>

<p>
  WHEREAS the School Building assistance program is the oldest capital grant program operated by the
  Commonwealth, as established in MGL Chapter 70B section 1; and
</p>

<p>
  WHEREAS the Massachusetts School Building Authority (MSBA) is charged with promoting the
  thoughtful planning and construction of school facility space in order to ensure safe and adequate
  facilities for public schools, and with assisting municipalities in meeting the cost thereof; and
</p>

<p>
  WHEREAS the MSBA has improved the learning facilities of over 600,000 students across the
  Commonwealth by working with local communities to create affordable, sustainable, and energy
  efficient schools; and
</p>

<p>
  WHEREAS the MSBA is limited in funding as stated in MGL 70B section 7, to $1,200,000,000 plus
  either the rate of growth in the dedicated sales tax revenue amount as defined in subsection a of
  section 35BB of chapter 10, or 4.5%; and
</p>

<p>
  WHEREAS the MSBA has declared a pause on their Accelerated Repair Program and limits on their Core
  Projects due to rising costs and inflation, and the need to stay within the Annual Cap as
  referenced in the Memorandum of October 19, 2022 from the MSBA Deputy Treasurer and Executive
  Director; and
</p>

<p>
  WHEREAS each year the Accelerated Repair Program is delayed results in an increase in application
  backlog among the Commonwealth&rsquo;s existing backlog of school building needs;
</p>

<p>
  THEREFORE BE IT RESOLVED that the Massachusetts Association of School Committees calls upon the
  Massachusetts Legislature to amend MGL ch.70B, section 7 by removing the $1,200,000,000 cap; and
</p>

<p>
  BE IT FURTHER RESOLVED that the Massachusetts Association of School Committees calls upon the
  Massachusetts School Building Authority to reinstate the Accelerated Repair program for 2024
  applications; and
</p>

<p>
  BE IT FURTHER RESOLVED that the Massachusetts Association of School Committees calls upon the
  Massachusetts Legislature to allow public preschools to be included in the Accelerated Repair
  Program and Core Program.
</p>

<p>MASC status update on this resolution</p>

<p>
  The MSBA reinstated the Accelerated Repair Program and maintains an alternating schedule to have
  Statements Of Interest every two years. Public Preschools may be included in the Accelerated
  Repair Program and Core Program so long as the building does not exclusively serve Preschool. The
  cap has remained at $1.2 billion (not taking into account year over year adjustments as outlined
  in MGL 70B section 7). In the FY24 budget, the legislature made adjustments related to the cap.
  This included raising the cap to $1.2 billion (up from $800 million); ensuring funding for the
  accelerated repair program would not count towards this cap; and allowed for the cap to rise year
  over year by as much as 6.5% up from 4.5%.
</p>

