<h3>RESOLUTION 1: SAFE ZONES</h3>

<p><em>(Submitted by the New Bedford School Committee)</em></p>

<p>
  WHEREAS it is the right of every child, regardless of immigration status, to access a free public
  preK-12 education and for the District to welcome and support all students; and
</p>

<p>
  WHEREAS the District has a responsibility to ensure that all students who reside within its
  boundaries, regardless of immigration status, can safely access a free public preK-12 education;
  and
</p>

<p>
  WHEREAS federal immigration law enforcement activities, on or around District property and
  transportation routes, whether by surveillance, interview, demand for information, arrest,
  detention, or any other means, harmfully disrupt the learning environment to which all students,
  regardless of immigration status, are entitled and significantly interfere with the ability of all
  students, including U.S. citizen students and students who hold other legal grounds for presence
  in the U.S., to access a free public K-12 education; and
</p>

<p>
  WHEREAS through its policies and practices, the District has made a commitment to a quality
  education for all students, which includes a safe and stable learning environment, means of
  transportation to and from school sites, the preservation of classroom hours for educational
  instruction, and the requirement of school attendance; and
</p>

<p>
  WHEREAS parents and students have expressed to the District fear and confusion about the continued
  physical and emotional safety of all students and the right to access a free public preK-12
  education through District schools and programs; and
</p>

<p>
  WHEREAS educational personnel are often the primary sources of support, resources, and information
  to assist and support students and student learning, which includes their emotional health;
</p>

<p>
  THEREFORE BE IT RESOLVED that MASC recommends to school districts to adopt a model policy that
  includes the following:
</p>

<p>
  The District shall interact with U.S. Immigration and Customs Enforcement (ICE), state or local
  law enforcement agencies acting on behalf of ICE, and any agents or officers of federal, state, or
  local agencies seeking to enforce federal immigration laws, strictly in accordance with the
  Massachusetts Attorney General&rsquo;s Guidance for Massachusetts Public Schools on Protecting
  Immigrant Students (incorporated into this Resolution), to ensure that the District fulfills its
  legal and moral obligation to provide all students, regardless of immigration status, access to a
  free public K-12 education.
</p>

<p>
  BE IT FURTHER RESOLVED that the Committee declares the District to be a Safe Zone for its
  students, meaning that the District is a place for students to learn, to thrive, and to seek
  assistance, information, and support related to any immigration law enforcement that interferes
  with their learning experience.
</p>

<p>
  BE IT FURTHER RESOLVED that the District shall, within 30 days of the date of this Resolution,
  create a Rapid Response Team to prepare in the event a minor child attending school in the
  District is deprived of adult care, supervision, or guardianship outside of school due to a
  federal law enforcement action, such as detention by ICE or a cooperating law enforcement agency.
</p>

<p>
  BE IT FURTHER RESOLVED that any request by ICE or other agencies to visit a school site should be
  presented to the Superintendent&rsquo;s Office for review as to whether access to the site is
  permitted by law, a judicial warrant is required, or any other legal considerations apply; this
  review should be made expeditiously, but before any immigration law enforcement agent or officer
  appears at a school site.
</p>

<p>
  BE IT FURTHER RESOLVED, in its continued commitment to the protection of student privacy, the
  District shall review its record-keeping policies and practices to ensure that no data is being
  collected with respect to students&rsquo; immigration status or place of birth; and cease any such
  collection as it is irrelevant to the educational enterprise and potentially discriminatory.
</p>

<p>
  BE IT FURTHER RESOLVED, should ICE or other immigration law enforcement agents request any student
  information, the request should be referred to the Superintendent&rsquo;s Office to ensure
  compliance with Family Educational Rights and Privacy Act (FERPA), student constitutional privacy,
  standards for a judicial warrant, and any other limitation on disclosure; this review should be
  conducted expeditiously, but before any production of information is made.
</p>

<p>
  BE IT FURTHER RESOLVED the District shall post this Resolution in the main office of every school
  and at all school sites, distribute it to District staff, students, and parents using the
  District&rsquo;s usual means of communication, and ensure that it is translated into all languages
  spoken in students&rsquo; homes.
</p>

<p>
  BE IT FURTHER RESOLVED the District shall make resources&mdash;such as Red Cards, mock warrants,
  and mock subpoenas&mdash;available in the main offices, guidance offices, wraparound centers, and
  administrative buildings, and shall ensure that these resources are regularly restocked and shall
  include links to these resources in its published versions of the policy.
</p>

<p>
  BE IT FURTHER RESOLVED the District shall offer &ldquo;Know Your Rights&rdquo; trainings and
  family preparedness sessions in collaboration with immigrant advocacy organizations and with links
  to these resources.
</p>

<p>
  BE IT FURTHER RESOLVED the District shall offer a Q&amp;A session for all District employees on
  the Attorney General&rsquo;s Guidelines.
</p>

<p>
  BE IT FURTHER RESOLVED that the Committee directs the Superintendent to review District policies
  and practices regarding bullying, harassment, and discrimination and report back to the Committee
  at its next meeting and communicate to staff, students, and parents the importance of maintaining
  a bullying/harassment/discrimination-free environment for all students.
</p>

<p>
  BE IT FURTHER RESOLVED the District shall work with department heads on integrating
  immigration-related content across disciplines.
</p>

<p>
  BE IT FURTHER RESOLVED the District shall minimize the presence of unfamiliar
  individuals&mdash;such as non-educators, police, security personnel, and other outsiders&mdash;on
  school sites.
</p>

<p>
  BE IT FURTHER RESOLVED the Committee affirms that licensed educators in the District have the
  academic freedom to discuss this Resolution during class time provided it is age-appropriate; and
  students are to be made aware that District counselors are available to discuss the subjects
  contained in this Resolution.
</p>

<p>
  BE IT FURTHER RESOLVED that after-school providers and other vendors and service providers who
  contracted with the District shall be notified of this Resolution within 30 days and be required
  to abide by it; and
</p>

<p>
  BE IT FURTHER RESOLVED that the Superintendent shall report back on compliance with this
  Resolution to the Committee at its next meeting.
</p>

<h3>
  RESOLUTION 2: VOCATIONAL/TECHNICAL REPRESENTATION ON THE MASSACHUSETTS BOARD OF ELEMENTARY AND
  SECONDARY EDUCATION
</h3>

<p><em>(Submitted by the Nashoba Valley Technical School Committee)</em></p>

<p>
  WHEREAS the Board of Elementary and Secondary Education has broad powers to set education policy
  and enact regulations for Massachusetts public schools; and
</p>

<p>
  WHEREAS the Massachusetts core curriculum is applied at Chapter 74 schools in a different manner
  than most comprehensive schools; and
</p>

<p>
  WHEREAS Chapter 74 programs have extensive technical specifications as well as OSHA regulations;
  and
</p>

<p>
  WHEREAS vocational/technical expertise is required for the safe and effective application of
  policies and regulations;
</p>

<p>
  THEREFORE BE IT RESOLVED that the Massachusetts Association of School Committees calls upon the
  Governor and the Legislature to add a seat to the Department of Elementary and Secondary Education
  board specifically for a representative with vocational/technical experience.
</p>

<h3>
  RESOLUTION 3: VOCATIONAL/TECHNICAL REPRESENTATION ON THE MASSACHUSETTS SCHOOL BUILDING AUTHORITY
  BOARD
</h3>

<p><em>(Submitted by the Nashoba Valley Regional Technical School Committee)</em></p>

<p>
  WHEREAS the Massachusetts School Building Authority (MSBA) is the established organization that
  assists public schools in the Commonwealth with building and renovation projects; and,
</p>

<p>
