<h3>School Committee Reports/Communications.</h3>

<h4>
  Dr. Grannemann: Continued discussion of
  <a href={Router.meetingItem(SEPTEMBER, "focus-areas-for-district-improvement")}>
    Focus Areas for District Improvement
  </a>.
</h4>

<p>
  Dr. Grannemann noted that the discussion had been started at the last meeting. He suggested that
  Haverhill should take a fresh look at how it uses the Multi-Tiered System of Support (MTSS),
  rather than focusing primarily on students needing the most intensive interventions, the district
  should provide meaningful support to the large group of students in the middle.
</p>

<p>
  Dr. Grannemann emphasized purpose, higher expectations, and commitment, with these applying to
  students, families, teachers, staff, and especially the School Committee. He added that student
  ownership particularly with older students, by encouragement to become more engaged and take
  greater responsibility for their education, with appropriate guidance and support.
</p>

<p>
  Ms. Collins underscored belonging and relationships by identifying connection, belonging,
  enjoyment, and relationships are critical to getting students to attend school and engage in
  learning. She recommended understanding students&rsquo; perspectives and suggested that district
  goals should better reflect what school feels like from the students&rsquo; point of view,
  including what motivates them to participate and do their best. Additionally, she proposed
  encouraging teacher creativity, whereby teachers would have more freedom to make curriculum
  relevant and engaging for individual students. Creative approaches can strengthen relationships
  while still meeting academic expectations.
</p>

