<h2>Minutes</h2>

<p><strong>85-E</strong></p>

<p>
  Mayor addressed the council. She suggested this get sent to a subcommittee for further discussion
  with Judi and Attorney Lisa Mead. Judi Barrett addressed the council. She noted the fiscal impact
  study results using actual FY25 data. The study estimates revenues and service costs for various
  potential land uses, not a specific project, requiring broad assumptions this excludes enterprise
  funds. She noted that mainly schools, police and fire experience significant cost increases from
  population or employment growth. She noted that using a mixed-use prototype (10 housing units and
  7500 s.f showed about 34,900 in revenue verses 22,000 in costs producing a positive fiscal impact.
  During the discussion, the council received a fiscal impact presentation regarding large-scale
  residential development and raised concerns about the accuracy and usefulness of project-level
  analyses. Councilors (Jordan, Michitson and Basiliere) emphasized the need for future reviews to
  include both fiscal impact analyses and development impact assessments, particularly for water and
  wastewater infrastructure. Questions were raised about inconsistent school expenditure data,
  enrollment impacts, and the reliability of assumptions used in projecting student generation
  rates. The consultant explained differences in state reporting requirements, factors that
  influence enrollment unpredictably after permitting, and the limitations of using standard models
  without project-specific context. Councilors expressed concern about receiving analysis materials
  too late for adequate review and requested earlier delivery for future projects.
</p>

