<p>Councilors Ferreira and Michitson wish to discuss pedestrian safety in Haverhill</p>

<h2>Minutes</h2>

<p><strong>33-Z</strong></p>

<p>
  Lt. Kevin Lynch addressed the council he noted that the past five years, the intersection on River
  Street and Hunter Avenue has seen 13 crashes, including sideswipes, rear-ends and turning
  collisions and the recent fatality still under investigation. The location poses safety challenges
  due to its position on a high-speed high volume state road near an exit ramp and small hill.
  Current guidance suggests that a crosswalk is not advisable under these conditions and MassDOT is
  evaluating options. Relocating the nearby bus-stop ideally onto West Lowell Avenue may be the most
  effective immediate solution. Councilor Ferreira noted she spoke with MVPC, and they confirmed
  that area has been flagged for safety concerns and will be included in MassDOT&rsquo;s next
  Transit Safety Improvement Cycle. Mayor noted she has also contacted Senator Payano and Rep.
  Vargas for added support. Lt. Lynch noted that the Winter Street area since January 2020 had 146
  crashes. He went into details about each crash and how many distracted drivers and
  pedestrians&rsquo; poor visibility, and failure to use crosswalks all contributed to incidents in
  this busy corridor.
</p>

<p>Councilor Ferreira presented her PowerPoint presentation.</p>

<p>
  Councilor Michitson noted he is mostly interested in coming up with a systematic way of getting
  some of these flashing beacons or some of the lower cost alternatives, maybe a five-year capital
  plan for that. Mayor Barrett stated come budget time we should think of this. Councilor Basiliere
  stated Winter Street sees a lot of cars, solar glare and has a high population of people.
  Councilor Lewandowski agrees to sending to Planning and Development when everyone works together
  solutions can be available with collaboration. Vice President Jordan stated light timing issue
  with the crosswalks would be helpful. He brought up Lincolnshire and Kingsbury Avenue
  intersection, Lt. Lynch noted next potentially a guardrail will go up. Vice President Jordan also
  noted the Kingsbury Avenue and Willow Avenue intersection I know it&rsquo;s on the radar. I would
  like it to stay on the radar.
</p>

<p>
  Motion by Councilor Michitson to send this to Planning and Development, second by Councilor
  Lewandowski<br />
  PASSED &ndash; Yeas 10, Nays 0, Absent 1 (Rogers)
</p>

