<h2>5.4.</h2>

<p>
  Mayor Barrett requests the City Council&rsquo;s support in advocating for the passage of Senate
  Bill 3077, <em>An Act to Enhance the Safe Use of Micromobility Devices</em>
</p>

<h2>15.1.</h2>

<p>
  Councilors Lewandowski, Toohey, and Vice President Michitson wish to discuss public safety,
  e-bikes and Governor Healey&rsquo;s Ride Safe Act
</p>

<h2>Minutes</h2>

<p><strong>City Clerk Wright: called up 15.1 with this item</strong></p>

<p>
  Councilors discussed growing public safety concerns related to the use of e-bikes and electric
  scooters, particularly by minors. Mayor Barrett announced that the City is drafting a local
  ordinance based in part on the Governor&rsquo;s proposed Ride Safe Micromobility Act. Councilor
  Lewandowski advocated for strengthening the ordinance by incorporating provisions that promote
  public education, safety, and awareness, referencing the recent death of a 12-year-old girl and
  the critical injury of another child. Lt. Kevin Lynch outlined proposed measures, including
  requiring licenses or learner&rsquo;s permits for certain devices, escalating impound penalties
  for repeat violations, possible parental fines, and prohibiting operation on sidewalks,
  recreational parks, school property, conservation areas, and other restricted locations, noting
  that riding e-bikes on sidewalks is already prohibited under state law. Councilor Toohey supported
  further review by the Traffic and Safety Subcommittee. Vice President Michitson supported local
  regulations addressing conduct, equipment, and enforcement while recommending that broader issues
  such as registration, licensing, insurance, and device standards remain under state jurisdiction.
  Councilor McGonagle suggested creating a safety training or certification program for younger
  riders who do not hold a learner&rsquo;s permit or driver&rsquo;s license. Councilor Diodati
  supported registration and licensing requirements and questioned whether children should be
  operating e-bikes. President Jordan emphasized that the issue has existed for some time, expressed
  support for prompt action, and suggested considering a minimum operating age of 16.
</p>

