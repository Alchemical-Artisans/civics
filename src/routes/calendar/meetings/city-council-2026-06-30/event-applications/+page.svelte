<h2>12.6.2.</h2>

<p>
  <strong>EVNT-26-19</strong>- Joseph LeBlanc for <em>Team Haverhill</em> requests to hold their
  annual <em>River Ruckus</em> event on Saturday September 12<sup>th</sup> from 9 AM to 9 PM at the Riverfront
  parking lot on Washington St. They request the closing of Washington St alcove for Community Corner,
  12 to 3 PM and the closing of Washington St for a car show, 12 to 3 PM and the closing of Columbus Park
  for Kids Zone. There will be fireworks at the close of the festival. They also request that police and
  fire detail costs be waived.
</p>

<h3>Minutes</h3>

<p>Moved to middle of agenda</p>

<p>
  Joseph LeBlance addressed the council. He stated the last line in the agenda item is important. He
  stated it costs us a lot to put on this day. He stated it is a fantastic day for everyone. He
  stated the headline act is Grace Potter. Councilor Ferreira asked in the past have you requested
  the Police and Fire details waived or is that new? Joseph LeBlanc stated that is not new.
  Councilor Ferreira asked do you have an estimate of that cost? Joseph LeBlanc stated please
  don&rsquo;t quote me on this but it is in the order of $10,000.00. President Jordan stated he
  doesn&rsquo;t think it is quite that much.
</p>

<p>
  MOTION BY COUNCILOR MCGONAGLE, SECOND BY VICE PRESIDENT MICHITSON<br />
  PASSED YEAS 11, NAYS 0, ABSENT 0
