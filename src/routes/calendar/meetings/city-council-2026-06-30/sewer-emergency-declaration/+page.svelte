<p>Mayor Barrett submits an order for emergency declaration and capital fund transfer</p>

<ul>
  <li>
    <strong>5.0.1.</strong> Order &ndash; Declaration of Emergency regarding the unexpected and extremely
    heavy rainstorm on June 26, 2026 that overloaded and ruptured the 42&rdquo; sewer force main located
    in the area of South Kimball St near Peabody St (Sewer Break), presenting an imminent risk to public
    health, and votes to transfer from Sewer Retained Earnings $2,500,000.00 to a new capital fund account
    (Sewer Pipe Emergency Capital Repair 06262026) for purpose of remediating, repairing, and constructing
    a repair to the Sewer Break including all necessary design, construction and related costs associated
    with the same
  </li>
</ul>

<h2>Minutes</h2>

<p>
  Mayor Barrett addressed the council. She updated the council on the emergency failure of the
  city&rsquo;s 42-inch wastewater/force main. She stated staff and contractors quickly started
  working on a temporary bypass system to restore wastewater flow while permanent repairs are
  planned. The temporary fix is estimated to cost 2 million to 2.5 million and will be funded
  through retained earnings. She noted that once a plan is in place for 42 inch main in the near
  future we will come to you and probably have to bond that out. Robert Ward presented photos at the
  site and described the situation with the pipe and the repairs taking place. He talked about the
  notification plan and how it is approved by DEP. He noted we have made all the notifications; we
  have been sending out updates. He noted we haven&rsquo;t been perfect because we have been busy,
  but they have been done.
</p>

<p>
  Councilors Sullivan, Toohey, Basiliere, Michitson, McGonagle, Diodati, Ferreira, and President
  Jordan questioned DPW Director Bob Ward and the Mayor regarding the wastewater force main failure,
  public health impacts, infrastructure condition, project costs, and long-term resiliency. Mr. Ward
  explained that public access to the river and beaches would be determined by state water quality
  testing, the City&rsquo;s drinking water system was not affected, and the failure could not have
  been reasonably anticipated despite significant investments in the wastewater system over the past
  decade. He estimated a permanent replacement could cost $12–15 million, with temporary bypass
  costs still being finalized, and noted that engineering evaluations are underway to ensure the
  replacement addresses the entire system. The Mayor stated the City&rsquo;s focus remains on
  resolving the issue and that any potential liability claims would be handled by the City
  Solicitor, while Councilors emphasized the need for continued infrastructure investment, public
  communication, and long-term planning to improve system reliability. Resident Andrea Watson
  commended the City&rsquo;s response, stating that after speaking with state agencies she was
  confident appropriate procedures were being followed.
</p>

