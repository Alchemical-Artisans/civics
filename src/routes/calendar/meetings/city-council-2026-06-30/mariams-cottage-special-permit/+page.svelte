<p>
  <strong>Doc 21-D - <PermitRecord number="CCSP-26-3" /></strong> - Attorney Jonathan Stark-Sachs for
  client Maryam Salehi-Ala-Yamin requests approval to operate &ldquo;Mariam&rsquo;s Cottage&rdquo; a family
  run bed and breakfast at 421 East Broadway allowed with a special permit in the RR (Rural Residential)
  zoning district and seeks to host small-scale weddings and similar outdoor events of up to 50 guests
  packaged with overnight stays
</p>

<p class="text-right"><strong><em>Continued from June 2, 2026</em></strong></p>

<AddressMap address="421 East Broadway, Haverhill, MA" lat={42.783045} lon={-71.024913} />

<h2>Minutes</h2>

<p><strong>President Jordan opened hearing</strong></p>

<p>
  Attorney Starks Sachs addressed the Council on behalf of the applicant, presenting the proposal to
  convert the historic cottage at 421 East Broadway into a family-operated bed and breakfast with
  accessory event use. <strong>(PowerPoint reviewed)</strong>. He explained that the home,
  originally built in 1817, had been restored after a two-year rehabilitation that preserved its
  historic character. He stated the project would provide a unique lodging option with minimal
  neighborhood and environmental impacts, improved site access, landscaping, and adequate on-site
  and overflow parking. He noted that the applicant is requesting conditions allowing small-scale
  accessory events, including occasional weddings, baby showers, engagement parties, workshops, and
  similar gatherings, with a maximum of 50 guests. Proposed conditions include permitting owner
  occupancy through the adjacent residence while both properties remain under common ownership;
  limiting events to 50 attendees; allowing no more than six events with over 40 guests per year,
  with appropriate notification to city staff; requiring that one or more rooms are rented in
  conjunction only with events with over 20 guests; prohibiting non-reservation, walk in services
  except for normal overnight stays; limiting outdoor music may not before 7:00 a.m. and after 10:00
  p.m.; requiring all events to conclude by 11:00 p.m.; and restricting overnight guest use of the
  porch and yard areas. He stated these measures, together with existing vegetation, a proposed
  six-foot privacy fence, and compliance with all City permitting and noise regulations, would
  minimize impacts on neighboring properties.
</p>

<p><strong>President Jordan asked if anyone would like to speak in favor.</strong></p>

<p>
  Dan Belanger (407 East Broadway) addressed the council in support of the proposal. He stated that
  the applicant had restored abandoned property and improved the neighborhood. While acknowledging
  neighbors&rsquo; concerns about traffic and safety, he said those issues did not justify denying
  the special permit and suggested they could be addressed through signage or enforcement of speed
  in the area. He also emphasized that Maryam would provide on-site oversight and concluded that bed
  and breakfast should be allowed to proceed unless problems arise in the future.
</p>

<p>
  Brian Philbrook (160 Merrimack Street) addressed the council as her former culinary instructor and
  program coordinator at Northern Essex Community College he submitted a letter in support of her
  application. The letter described Maryam as hardworking, professional, and dedicated, highlighting
  her strong work ethic, hospitality skills, and experience serving the community through catering
  and hospitality events. He also expressed confidence in her ability to successfully operate a bed
  and breakfast and noted that the venture could provide future internship and employment
  opportunities for culinary and hospitality students.
</p>

<p>
  Guylaine Beaulieus (639 East Broadway) addressed the council. She stated she is in support of the
  proposal. It is a positive addition to the neighborhood. After visiting the property, she
  expressed a strong approval of its setting and potential benefit to East Broadway.
</p>

<p><strong>President Jordan asked if anyone would like to speak in opposition.</strong></p>

<p>
  Tim Sturgeon (419 East Broadway) addressed the council. He stated bathrooms were added and rooms
  decorated a certain way and was built as a bed and breakfast from the beginning. I am opposed to
  the proposal, citing lack of neighborhood notification and concerns about commercial use in a
  residential area. He raised issues related to noise, events, privacy, and enforcement stating that
  the proposed conditions would not adequately protect neighborhood properties.
</p>

<p>
  Judith Biewener (419 East Broadway) addressed the council. She stated she is opposed to this
  proposal. Citing concerns that commercial events would increase traffic, noise and activity. This
  would alter the rural residential character and negatively impact nearby homes. She urged the
  council to consider the impact on neighbors and noted that written comments had been submitted.
</p>

<p>
  Lisa Onyon (400 East Broadway) addressed the council. She urged the council to preserve the
  neighborhood rural residential character and deny the special permit. She expressed concern for
  setting a precedent for future businesses, enforcement of permit conditions, noise, environmental
  impacts, and the applicant&rsquo;s advertising a bed and breakfast before obtaining required
  approvals.
</p>

<p>
  Attorney Stark Sachs addressed the council. He stated I think there was confusion over the
  permitting process, the business never violated the zoning ordinance. He noted the extensive
  outreach and discussions with city staff and neighbors that had taken place and expressed a
  willingness to work with the City Council to establish reasonable operating conditions for the
  special permit.
</p>

<p>
  Attorney Russell Channen addressed the council. He stated while the applicant&rsquo;s character
  was not in question, the proposal did not demonstrate a community need under Section 10.4.2. He
  also expressed concerns about the rural location, potential noise impacts, and that a bed and
  breakfast is not an appropriate use for the site.
</p>

<p><strong>President Jordan closed the hearing.</strong></p>

<p>MOTION BY COUNCILOR SULLIVAN FOR PASSAGE, SECOND BY COUNCILOR FERREIRA</p>

<p>
  During council discussion, Councilor McGonagle thanked both supporters and opponents for their
  input but stated he would oppose the proposal, citing concerns that the proposed use would
  generate excessive traffic and parking for the neighborhood. Councilor Lewandowski praised the
  appearance of the property and the owner&rsquo;s vision but expressed concerns about large events
  in a residential area, stating she could support a smaller-scale operation. The applicant&rsquo;s
  son Arash Arman responded that the proposal would result in only a minimal increase in traffic,
  operate for no more than six months each year, and host fewer than 50 attendees. He also addressed
  concerns regarding a previous wedding held at the property and stated the applicants were willing
  to accept reasonable conditions.
</p>

<p>
  Councilor Ferreira voiced her support, stating the proposal was appropriately scaled, created a
  small business opportunity, and included reasonable conditions to mitigate impacts. Councilor
  Rogers said she could support a smaller version of the proposal but opposed the backyard tent and
  larger events, recommending activities be limited to the house and deck. Councilor Sullivan
  supported the bed-and-breakfast concept but suggested removing the event component, believing it
  would improve the proposal&rsquo;s chances for approval while minimizing neighborhood impacts.
  Councilor Diodati supported the application, stating it preserved the historic character of the
  area, would not significantly alter the neighborhood, and represented a valuable restoration
  project. Councilor Toohey expressed support for the concept on a smaller scale. Attorney Starks
  Sachs clarified that if either property were sold separately, the special permit would expire
  unless reconsidered and approved again.
</p>

<p>
  Vice President Michitson stated he supported a traditional, scaled-down bed and breakfast but
  remained concerned about the proposed size, neighborhood impacts, noise, and potential effects on
  surrounding property values. Councilor Basiliere also supported the proposal but suggested
  reducing the guest capacity for events as a possible compromise. Councilor LePage supported the
  bed-and-breakfast use but recommended allowing the business to demonstrate successful operation
  before expanding into additional event-related activities. President Jordan thanked everyone for
  their comments, acknowledged the concerns raised by both supporters and opponents, and noted that
  approval would require eight affirmative votes. He suggested possible modifications, including
  limiting events or approving the proposal on a trial basis, as potential ways to address
  neighborhood concerns.
</p>

<p>
  Attorney Starks Sachs suggested possible revision of limiting events to 25-30 people and
  containing activities primarily within the home and porch area.
</p>

<p>
  Councilor Lewandowski stated she would feel comfortable voting tonight on Bed and Breakfast,
  classes and small gatherings of 10-15 guests, with the option to revisit expansion later.
  Councilor Toohey stated I am in 100% agreement. He stated it would be a hard no on any events.
  Councilor Toohey and Lewandowski stated no tents, no events parking, no music, no porta potties.
</p>

<p>
  Maryam Yamin stated what if we skip weddings for a trial for 2 years. She stated the work I put
  into this project and at this stage I really want to give something back to my town. She noted
  this will be different than any other bed and breakfast. It is going to be elevated. The business
  will be run by myself and my children. It won&rsquo;t be loud. We won&rsquo;t have any porta
  potties, tents and no parking issues.
</p>

<p>
  Councilor Sullivan stated he is not sure we can get there tonight. He thinks we need to allow the
  applicant to refine their proposal and come back before us given the information that was
  presented.
</p>

<p>
  President Jordan stated Councilor Sullivan you made the motion to approve this, and Councilor
  Ferreira seconded it. Are you suggesting different a motion to table.
</p>

<p>
  MOTION BY COUNCILOR SULLIVAN TO TABLE THIS TO A FUTURE DATE FOR A MODIFIED PROPOSAL, SECOND BY
  COUNCILOR FERREIRA
</p>

<p>
  Councilor McGonagle stated he would like to hear their answer if they would like to come back or
  if they would like a vote.
</p>

<p>Attorney Starks Sachs stated it sounds appropriate to come back on another night.</p>

<p>
  MOTION BY COUNCILOR SULLIVAN TO CONTINUE THIS MATTER FOR A MODIFIED PROPOSAL TO THE JULY 28, 2026
  MEETING. SECOND BY COUNCILOR FERREIRA
</p>

