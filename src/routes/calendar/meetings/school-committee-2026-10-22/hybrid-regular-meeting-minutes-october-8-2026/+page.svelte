<p>
  Dr. Marotta introduced Jami Dion, Director of Guidance, Counseling and Student Support Services
  and Meg Arivella, Supervisor of School Counseling to speak on the new MindUp curriculum for social
  emotional learning.
</p>

<p>Ms. Dion provided a several key points the MindUp curriculum:</p>

<ul>
  <li>
    new <strong>brain-based, Social-Emotional Learning (SEL) curriculum</strong> being pushed into classrooms
    by guidance counselors.
  </li>
  <li>
    Teachers attend these lessons alongside students to learn the content, language, and strategies,
    enabling them to carry the practices forward daily.
  </li>
  <li>
    Counselors are focusing their professional development on MindUp to build a comprehensive scope
    and sequence across all grade levels.
  </li>
  <li>
    <strong>Core Objectives:</strong>
    <ul>
      <li>
        <strong>Brain Function &amp; Self-Regulation:</strong> Teaches students how their brain functions
        (including learning parts of the brain like the amygdala and hippocampus) and how brain activity
        influences emotions. This helps improve focus, manage stress, and build impulse control.
      </li>
      <li>
        <strong>Perspective Taking &amp; Compassion:</strong> Builds empathy through sensory awareness
        and kindness to reduce maladaptive behaviors, peer indifference, and teasing.
      </li>
      <li>
        <strong>Accountability &amp; Ownership:</strong> Empowers students to take responsibility for
        their actions and maintain positive relationships.
      </li>
    </ul>
  </li>
  <li>
    <strong>Alignment with CASEL Competencies:</strong>
    <ul>
      <li>
        Every MindUp lesson aligns with one or more of the 5 CASEL competencies:
        <ol>
          <li>Self-awareness</li>
          <li>Self-management</li>
          <li>Social awareness</li>
          <li>Relationship skills</li>
          <li>Responsible decision-making</li>
        </ol>
      </li>
    </ul>
  </li>
</ul>

