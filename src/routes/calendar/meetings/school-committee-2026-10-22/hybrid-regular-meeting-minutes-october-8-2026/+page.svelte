<h3>JGW/Tilton School Building Updates.</h3>

<p>
  Superintendent Marotta outlined that the school building project was moving into the design phase,
  with an architect and Owner&rsquo;s Project Manager (OPM) hired for the project. She summarized
  three enrollment options are under consideration:
</p>

<ul>
  <li>745 students: A middle school serving JGW with additional space and classrooms.</li>
  <li>
    1,045 students: A grades 4&ndash;8 school that would involve closing Tilton School and adjusting
    attendance boundaries.
  </li>
  <li>
    1,325 students: A larger grades 3&ndash;8 school that would also involve closing Tilton and
    shifting attendance boundaries.
  </li>
</ul>

<p>
  Dr. Marotta indicated that the district was evaluating boundary changes and plans to share details
  with the community at upcoming public meetings. She announced that the building project has been
  approved to proceed through the Massachusetts School Building Authority (MSBA) process, with
  further approvals, including voter approval, potentially required for the building project. The
  superintendent explained a building committee meeting was scheduled for
  <a href={Router.meeting("john-greenleaf-whittier-school-building-committee-2026-10-14")}>
    October 14, 2026
  </a>, followed by a public meeting at Whittier School on November 5, 2026, to present plans,
  answer questions, and gather community feedback. Dr. Marotta revealed the project was expected to
  take several more years, with substantial completion anticipated around 2031&ndash;2032. She
  specified that the MSBA is expected to reimburse approximately 80% of eligible building costs.
</p>

<p>
  Mayor Barrett clarified that the building project was a lengthy one and would involve many public
  and community meetings.
</p>

