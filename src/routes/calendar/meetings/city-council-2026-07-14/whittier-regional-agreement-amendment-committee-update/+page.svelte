<h2>Minutes</h2>

<p>
  Council heard a presentation from Mayor Barrett and Salisbury Town Manager Neil Harrington
  regarding ongoing negotiations for a new regional agreement and the proposed construction of a new
  Whittier Regional Vocational Technical High School. Mayor Barrett highlighted the advantages of
  the NECC site, including lower infrastructure costs, existing utilities, workforce partnership
  opportunities, and potential state funding, while Neil Harrington outlined a proposed 50/50 hybrid
  funding formula that balances the current funding method with student enrollment. He noted the
  compromise would help keep Haverhill&rsquo;s cost near the target. Vice President Michitson
  expressed support for the proposal as a reasonable starting point, and Councilor Basiliere voiced
  support for constructing the new school, citing the long-term financial benefits of building.
  Councilor LePage expressed support for continuing negotiations and indicated he was open to the
  proposed changes to the regional agreement, including a two-thirds voting requirement with
  consideration of an opt-out provision to help move the project forward. Councilors Sullivan and
  Rogers asked questions regarding support among the member communities and the proposed two-thirds
  voting requirement for future agreement changes. President Jordan commended Mayor Barrett and
  Harrington for their collaborative efforts and expressed support for the compromise, including the
  50/50 funding proposal, hold harmless provision, and partnership with Northern Essex Community
  College.
</p>

