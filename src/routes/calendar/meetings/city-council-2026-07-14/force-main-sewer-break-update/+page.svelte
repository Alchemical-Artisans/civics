<p>
  Mayor Barrett requests Robert E. Ward, <em>Director of Water/Wastewater</em>, to provide an update
  on the 42&rdquo; force main sewer break
</p>

<h2>Minutes</h2>

<p>
  Robert Ward and Mayor Barrett addressed the council. Presented a PowerPoint presentation. He
  provided an update on June 26<sup>th</sup> force main failure and emergency response efforts. The
  failure of the 42&rdquo; force main resulted in untreated wastewater discharge into the Merrimack
  River, however, drinking water remained safe and emergency measures were implemented immediately.
  A temporary bypass pumping system was installed and is operating successfully while inspections,
  evaluations, and repair planning continue. Contractors are assessing repair and replacement
  options, with the bypass system remaining in place until permanent repairs are complete. He noted
  that inspections identified two pipe failures, including a damaged steel cylinder and areas
  showing exposed steel wires and corrosion. He stated as of July 1<sup>st</sup> there was no longer significant
  discharge to the river and normal sewer service had resumed. He stated the city has also submitted a
  required force main assessment plan to EPA and DEP and is reviewing long term resiliency improvements
  to help prevent future sewer overflow events. Vice President Michitson commended everyone involved for
  their swift response in restoring service during the major infrastructure failure. He also stated he
  is concerned with the risks associated with aging and vulnerable infrastructure and motioned to refer
  the matter to the Planning and Development Committee. The motion directs the committee to work with
  administration and appropriate departments on an initial risk-based assessment of city&rsquo;s critical
  infrastructure, beginning with the wastewater and drinking water systems. He noted this is a proactive
  approach aligning with the Mayor&rsquo;s 10-year budget/capital improvement plans and will help with
  future decisions. He noted that the assessment should identify critical assessments and single points
  of failures that could significantly impact public health, the environment, essential services and city
  finances. He also stated the initial phase should be reported to the City Council by the end of the
  year with a preliminary ranking of the highest risk and then after that provide a scope, schedule and
  cost for the next phase.
</p>

<p>
  Councilor Basiliere stated that while the exact cause remains undetermined, research on aging
  sewer infrastructure suggests intense rainfall can create hydraulic pressure that bursts pipes.
  Councilor Rogers asked if they were leaning towards a temporary fix or replace the whole line?
  Robert Ward confirmed right now I am leaning towards replacing the whole line. Councilor Rogers
  stated we wouldn&rsquo;t be able to remove the pumps until we do the major fix. If you do remove
  the pumps would you keep the old lines above ground for backup. Robert Ward stated no we
  wouldn&rsquo;t. President Jordan asked about efforts from Congresswoman Trahan and Congressman
  Moulton to seek potential funding for improvements. Mayor reported that members of the
  congressional delegation are pursuing potential federal funding. She noted the outcome remains
  uncertain given the current congressional environment any assistance would help accelerate
  repairs. She is hopeful there are grant opportunities that the city could apply for.
</p>

<p>
  Motion by Vice President Michitson to send to Planning and Development to work with the
  Administration and appropriate departments on an initial risk based assessment of the city&rsquo;s
  critical infrastructure beginning with the wastewater and drinking water systems. Second by
  Councilor Lewandowski<br />
  PASSED &ndash; Yeas 9, Nays 0, Absent 2 (Toohey and Diodati)
</p>

