<p>
  We were recently informed by Ruling Elder Ann Locniskar of the First Presbyterian Church of
  Haverhill that the building is currently for sale and that we would likely be unable to use the
  building for elections this year. To avoid voter confusion, my office seeks to change the polling
  location before the election cycle gets underway to ensure that we have time to notify as required
  by law.
</p>

<p>
  State election law requires the polling location be either in the precinct or the adjacent
  precinct, which significantly limits the suitable locations available to us. Therefore, we will
  need to move Ward 5, Precinct 2 to the Julian Steele Community Room and move the current precincts
  there (Ward 5, Precinct 1 and 1A and Ward 7, Precinct 2A) to Consentino Middle School. I am
  requesting the City Council approve this request to change the polling locations and designate the
  above-mentioned locations as polling locations for the remainder of the 2026 calendar year.
</p>

<p>Thank you for your consideration.</p>

<p>Respectfully,<br />Kaitlin M. Wright Esposito, CMC<br /><strong>City Clerk</strong></p>

