<p>
  BE IT ORDERED by the City Council of the City of Haverhill that the City Council votes to amend
  Chapter 240, Article V, &sect; 240-24 (&ldquo;All-night parking&rdquo;) of the Code of the City of
  Haverhill by adding the language denoted as emboldened as outlined in the following ordinance:
</p>

<h2>&sect; 240-24. All-night parking.</h2>

<p>
  A. Except as otherwise provided in this section, no person shall allow, permit or suffer any
  vehicle registered in his name, other than one acting in an emergency, to be parked on any street
  for a period longer than one hour between the hours of 6:00 p.m. and 6:00 a.m. at any time between
  <strong>December</strong>
  <del>November</del>
  15 and <strong>March 15</strong>
  <del>April 1</del><strong
    >, or such dates as determined by the Mayor and approved by City Council in conformance with
    paragraph D below.</strong
  >. [Amended 4-13-1993 by Doc. 26-C; 1-30-1996 by Doc. 18-C].
</p>

<p>
  B. It shall be lawful to park any vehicle on alternate sides of all streets in those zoning
  districts known as RH, RL, RM and RU between the hours specified in Subsection A above as follows,
  <strong
    >unless otherwise amended by the Mayor and approved by the City Council in conformance with
    paragraph D below</strong
  >: [Amended 4-20-1981 by Doc. 11-E; 1-30-1996 by Doc. 18-C]
</p>

<ol>
  <li>
    Beginning <strong>December</strong> <del>November</del> 15 at 6:00 p.m., even-numbered side of the
    street; and
  </li>
  <li>Beginning January 1 at 6:00 p.m., odd-numbered side of the street;</li>
  <li>Beginning February 1 at 6:00 p.m., even-numbered side of the street; and</li>
  <li>Beginning March 1 at 6:00 p.m., odd-numbered side of the street.</li>
</ol>

<p>
  C. This section shall not apply to any automobiles bearing a license number plate beginning with
  &quot;HP&quot; or &quot;V,&quot; except during snow removal or snow plowing activity.
</p>

<p>
  D. <strong
    >In any year the Mayor may modify the start and end dates of the all-night parking ban and
    exceptions under Subsection B, subject to final approval by the City Council. Changes to any
    dates in Subsection A or Subsection B may not take effect unless they are published on the City
    website and through the same news and media sources used to declare a snow emergency no less
    than 7 days prior to November 15, and unless the first day of the parking ban is no less than 7
    days after the date of initial publication.</strong
  >
</p>

<p>
  E. Any citizen or citizens may petition the City Council for an alternate parking plan on their
  respective streets. Permission may be granted at the discretion of the City Council.
</p>

