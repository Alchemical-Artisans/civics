<h2>Authority to File</h2>

<p>
  Whereas, City of Haverhill, (the Applicant), after thorough investigation, has determined that the
  work activity consisting of engineering and construction related to the South Mill Street Pumping
  Station force main is both in the public interest and necessary to protect the public health, and
  that to undertake this activity, it is necessary to apply for assistance; and
</p>

<p>
  Whereas, the Massachusetts Department of Environmental Protection (MassDEP) and the Massachusetts
  Clean Water Trust (the Trust) of the Commonwealth of Massachusetts, pursuant to Chapter 21 and
  Chapter 29C of the General Laws of the Commonwealth (Chapter 21 and Chapter 29C) are authorized to
  provide financial assistance to municipalities for the purpose of funding planning and
  construction activities relative to Water Pollution Abatement Projects and Drinking Water
  Projects; and
</p>

<p>
  Whereas, the Applicant has examined the provisions of the Act, Chapter 21 and Chapter 29C, and
  believes it to be in the public interest to file a loan application.
</p>

<p>NOW, THEREFORE, BE IT RESOLVED by the City Council of the City of Haverhill as follows:</p>

<ol>
  <li>
    That the Mayor is hereby authorized on behalf of the Applicant to file applications and execute
    agreements for grant and/or loan assistance as well as furnishing such information, data and
    documents pertaining to the applicant for a grant(s) and/or loan(s) as may be required; and
    otherwise to act as the authorized representative of the Applicant in connection with this
    application;
  </li>
  <li>
    That the purpose of said loan(s), if awarded, shall be to fund planning and construction
    activities.
  </li>
  <li>
    That if said award is made the Applicant agrees to pay those costs which constitute the required
    Applicant&rsquo;s share of the project cost.
  </li>
</ol>
