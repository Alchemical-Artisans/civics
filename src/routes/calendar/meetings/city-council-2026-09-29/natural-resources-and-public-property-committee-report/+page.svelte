<h2>Minutes/Summary of the Natural Resource and Public Property Committee Meeting</h2>

<p>September 14, 2026</p>

<p>
  A Natural Resource and Public Property Meeting was held on Monday, September 14, 2026 at 6:00 PM
  in the City Council Chambers, Room 202
</p>

<p>
  Committee Members Present: Committee Chair, Melissa Lewandowski, Councilor Devan Ferreira (arrived
  late) and Councilor Ralph Basiliere
</p>

<p>Committee Members Absent: None</p>

<p>Councilors Present: None</p>

<p>
  City Officials: Mayor Melinda Barrett, Robert Moore, Conservation Department, Ben Delaware,
  Recreation Department, City Solicitor Lisa Mead, Richard MacDonald, Inspectional Services
  Department, Robert Moore, Conservation Department and Nick Alyward, DPW Department
</p>

<p>The following items were discussed:</p>

<ul>
  <li>
    Doc. 12-c Motion by Councilor McGonagle to refer fixed vendor locations for further discussion
  </li>
  <li>
    <a href={Router.meetingItem("city-council-2026-08-25", "vegetation-management-plan")}>
      Doc. 41-a Motion by Councilor Ferreira to send for further discussion an overview of the
      city&rsquo;s vegetation management plan</a
    >
  </li>
</ul>

<p>
  Chair Lewandowski stated that a previous Council discussion addressed fixed vendors and a proposal
  to allow multiple vendors at Riverside Park, GAR Park, Bradford Common, Plug Pond, and Riverfront
  Park. Concerns included pedestrian traffic, impacts on downtown businesses, and trash/debris.
  Councilor Basiliere stated that current demand may not support a significant increase in vendors
  and proposed a compromise.
</p>

<p>
  <em
    >Motion by Councilor Basiliere two additions and condition it with the vendors have to move
    their trash, remove it from the public property and dispose it of your own volition.</em
  >
</p>

<p>
  Councilor Basiliere stated that doubling the number of vendors and adding additional sites may be
  excessive. Chair Lewandowski agreed and discussed the proposed use of Plug Pond with Ben Delaware,
  who noted that the beach is only open for approximately two and a half months each year and may
  not be an ideal location for a vendor. Chair Lewandowski asked Attorney Lisa Mead to clarify the
  definition of a fixed vendor, and Attorney Mead explained that the ordinance definition is the
  same, but we would add the wording &ldquo;shall not include bona fide nonprofit, civic,
  charitable, and youth organizations conducting occasional fundraising events&rdquo;. Attorney Mead
  reviewed the proposed vendor locations, including two at Riverside Park, one at GAR Park, two at
  Swasey Park, and one outside Haverhill Stadium at Lincoln and Nettleton Avenue, with no changes
  proposed for Winnekenni, Bradford Common, or Washington Square and no vendors proposed for
  Riverfront Park or Plug Pond. Attorney Mead noted that the ordinance would remain flexible and
  allow a vendor to request a location not specifically listed. Chair Lewandowski expressed concern
  about that location being incident heavy and vendor trucks could pose additional challenges,
  safety wise.
</p>

<p>
  <em>Motion by Councilor Basiliere to remove the vendor at GAR Park (Section 191-11 (5).</em>
</p>

<p>
  Chair Lewandowski asked if anyone from the public wished to speak on vendor locations. No one
  spoke.
</p>

<ul>
  <li>
    <a href={Router.meetingItem("city-council-2026-08-25", "vegetation-management-plan")}>
      Doc. 41-a Motion by Councilor Ferreira to send for further discussion an overview of the
      city&rsquo;s vegetation management plan</a
    >
  </li>
</ul>

<p>
  Nick Alyward, DPW Department addressed the committee and engaged in a discussion with Chair
  Lewandowski, responding to her questions and providing clarification. He noted the current plans
  run through 2027, with herbicide applied once a year over three nights, primarily along roadway
  edges to control poison ivy and overgrowth. Spraying is done overnight by a licensed contractor,
  and requires a 48-hour newspaper notice. Chair Lewandowski asked about specific spraying
  locations, signage, public input for the vegetation plan. The next update will be around the end
  of December 2027.
</p>

<p>
  <em
    >Motion by Councilor Basiliere to send the vegetation plan back to DPW and Conservation for
    their review of the contract and process and to have those departments notify the council for
    those interested in attending the meeting.</em
  >
</p>

<p><em>Councilor Ferreira joined the meeting</em></p>

<p>
  <em
    >Motion by Councilor Basiliere stated I would move that we send this matter back to the
    appropriate departments for review of the Vegetation Management Plan and see where we would be
    able to make improvements and requirements relative to herbicide application.</em
  >
</p>

<p>Chair Lewandowski asked if anyone else would like to speak. No one spoke.</p>

<p>
  Councilor Ferreira raised concerns regarding the City&rsquo;s yearly operating plan and the
  identification of a licensed pesticide applicator for vegetation management. She noted that the
  2026 plan lists the City as responsible for applying and managing herbicides but does not identify
  a licensed applicator. Nick Alyward stated that the City does have a licensed applicator.
  Councilor Ferreira also noted the plan references to public notification and spray records and
  requested greater transparency regarding herbicide use and vegetation management. Attorney Mead
  clarified that the City uses herbicides rather than pesticides, while Councilor Ferreira noted
  that herbicide application falls under state pesticide licensing requirements. Councilor Ferreira
  also expressed concerns regarding an herbicide application at Plug Pond this summer and requested
  that the City review its procedures and consider additional public notification and opportunities
  for public input. She suggested that the matter could be further discussed by the subcommittee or
  through a public comment process.
</p>

<p>
  Councilor Ferreira questioned the lack of a licensed applicator or contractor identified in the
  YOP. Nick Alyward stated the information is maintained in required records. Chair Lewandowski
  asked Nick to insert the identification of subcontractor holding license into the vegetation plan
  and report back to committee members on that change and we can go from there to identify other
  areas to tweak and enhance the plan Councilor Ferreira also raised concerns about herbicide use
  near Plug Pond and other public areas. Nick Alyward stated he confirmed with the City&rsquo;s
  representative that application is permitted more than 10 feet from the water line. Chair
  Lewandowski suggested improved public notification and signage and requested that Conservation be
  involved in reviewing herbicide use, application practices, and compliance with state
  requirements.
</p>

<ul>
  <li>
    Doc. 12-c Motion by Councilor McGonagle to refer fixed vendor locations for further discussion
    (discussed again with Councilor Ferreira being present)
  </li>
</ul>

<p>
  <em
    >Motion by Councilor Basiliere to send this to the full council that the modifications would be
    that we strike GAR Park, we add 1 at Riverside Park and 1 at Swasey Field.</em
  >
</p>

<p>
  Councilor Ferreira stated she prepared a PowerPoint presentation and received feedback from
  Recreation, Inspectional Services, and the Police Department, which expressed no concerns with the
  proposed increase in vendors. She noted Riverside Park is over 50 acres and stated that allowing
  more than two vendors is reasonable given the size and use of the park. Her proposal also included
  protections for city spaces, with the Clerk&rsquo;s Office providing maps identifying vendor
  locations and any site-specific rules. Mayor Barrett suggested having Ben review the proposed
  locations. Councilor Ferreira added that not all vendors would be food vendors and that the
  additional Riverside Park spaces were intended to provide food options where there are few
  storefronts. Chair Lewandowski stated that four vendors inside the stadium and two outside seemed
  excessive and noted the motion could be sent back to the full Council for further discussion by
  location.
</p>

<p>
  <em
    >Motion by Councilor Basiliere to bring this back to City Council for further discussion. Second
    by Councilor Ferreira</em
  >
</p>

<p>3 YEAS, 0 NAYS<br />PASSED</p>

<p>Chair Lewandowski stated this meeting is adjourned. 20.00</p>

