<h2>Minutes</h2>

<p>
  Mayor Barrett told the council the agreement strengthens police professionalism and public safety
  through body-worn cameras, improved scheduling, education and language incentives, and a continued
  focus on training and accountability. President Jordan thanked those involved, supported body
  cameras for accountability and officer exoneration, raised concerns about mental-health social
  work coverage, and questioned camera costs; Mayor Barrett responded that a social worker will be
  refilled January 26, wellness services expanded, 95% of officers are crisis-trained, and grant
  funding is being pursued, noting storage is the largest expense and regional options are being
  explored with Rep. Vargas. Councilor LePage commended the Mayor and union and cited personal jury
  duty experience showing body cameras tell the full story, while Councilor Lewandowski, a former
  prosecutor, emphasized cameras as ironclad evidence that improves officer safety, the judicial
  process, and community relations, asking about website transparency; Mayor Barrett said policies
  will be posted and several steps remain before rollout. Councilor Basiliere detailed extensive
  research and meetings, highlighted benefits of the 4x4 schedule, education incentives, reduced
  violence and complaints, and noted that roughly 85% of footage reviews exonerate officers,
  reducing city liability; he confirmed cameras must be implemented within six months of receiving
  the anticipated grant and supported the contract as improving public safety.
</p>

<p>
  Motion by Councilor Sullivan to approve, Second by Councilor Rogers<br />
  PASSED &ndash; Yeas 10, Nays 0, Absent 1 (McGonagle)
</p>

