<p>Mayor Barrett submits for approval the amended Haverhill Housing Production Plan</p>

<h2>Minutes</h2>

<p>
  Mayor Barrett, Councilors Michitson, Lewandowski, Diodati, Ferreira, Rogers, Sullivan, and
  Basiliere, along with Council President Jordan, participated in a discussion of the updated
  housing plan, which incorporates feedback from prior City Council and subcommittee meetings and
  support from the Merrimack Valley Planning Commission. Mayor Barrett noted the plan provides
  Chapter 40B protection, supports funding and grant eligibility, and meets state requirements,
  while MVPC&rsquo;s Ian Burns reported the city is currently 52 affordable units short of the 10%
  threshold. Councilors and staff discussed the need for an implementation strategy, infrastructure
  considerations, housing trust funds, senior housing initiatives, and the importance of state and
  federal funding, emphasizing that the plan is aspirational in nature and that partnerships and
  homeownership opportunities are key to advancing affordable housing and generational wealth.
</p>

<p>
  Motion by Councilor Ferreira to approve the Housing Production Plan with the condition for a
  yearly progress update on the plan, Second by Councilor Sullivan<br />
  PASSED &ndash; Yeas 10, Nays 0, Absent 1 (McGonagle)
</p>

