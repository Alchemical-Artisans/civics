</p>

<h2>Proclamation &ndash; Martin Luther King Day</h2>

<p>
  <strong>WHEREAS:</strong> Dr. Martin Luther King, Jr. devoted his life to advancing equality, social
  justice, and opportunity for all, and challenged all Americans to participate in the never-ending work
  of building a more perfect union; and
</p>

<p>
  <strong>WHEREAS:</strong> Dr. King&rsquo;s teachings continue to guide and inspire us in addressing
  challenges within our community; and
</p>

<p>
  <strong>WHEREAS:</strong> The King Holiday and Service Act, enacted in 1994, designated the King
  Holiday as a national day of volunteer service and charged the
  <a href="https://americorps.gov/" target="_blank" rel="external noopener noreferrer"
    >Corporation for National and Community Service<span class="sr-only">, opens in a new tab</span
    ></a
  > with leading this effort; and
</p>

<p>
  <strong>WHEREAS:</strong> Serving on the King Holiday is an appropriate way to honor Dr. King, meet
  local and national needs, bring our citizens together, and strengthen our communities and nation; and
</p>

<p>
  <strong>WHEREAS:</strong> The King Day of Service is the only federal holiday commemorated as a national
  day of service and offers an opportunity for Americans to give back to their communities on the holiday
  and make an ongoing commitment to service throughout the year; and
</p>

<p>
  <strong>WHEREAS:</strong> The citizens of Haverhill, Massachusetts, have an opportunity to participate
  in events throughout our state on the King Day of Service, January 19, 2026, as well as create and implement
  community service projects where they identify a need;
</p>

<p>
  <strong>NOW, THEREFORE, I, MELINDA E. BARRETT</strong>, Mayor of the City of Haverhill, do hereby
  proclaim the Martin Luther King, Jr. Day as a Day of Service in Haverhill and call upon the
  residents of the city to pay tribute to the life and work of Dr. King through participation in
  community service projects on the holiday and throughout the year.
</p>

<p>
  <em>
    IN WITNESS WHEREOF, I have set my hand and caused the seal of the City of Haverhill,
    Massachusetts to be affixed on this 19<sup>th</sup> day of January in the Year of Our Lord, Two Thousand
    and Twenty-Six
  </em>
</p>

<h2>Minutes</h2>

<p>Vice President Michitson read the proclamation into the record.</p>

<p>
  Motion by Vice President Michitson, Second by Councilor Sullivan<br />
  PASSED &ndash; Yeas 10, Nays 0, Absent 1 (McGonagle)
</p>

