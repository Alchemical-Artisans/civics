<p>
  <strong>Doc 100</strong> &ndash; Revocation hearing relative license issued to
  <em>Broco Energy relative to</em> <strong>SPFL-25-2</strong>, due to failure to notify abutters
  within the statutory deadline
</p>

<AddressMap address="168 Hale Street, Haverhill, MA" lat={42.7847879} lon={-71.0899268} />

<h2>Minutes</h2>

<p>*moved to beginning of hearing*</p>

<p>President Jordan opened the hearing.</p>

<p>
  President Jordan noted this hearing is to revoke what was approved in their increase due to the
  fact abutters were not notified. This is not a hearing to discuss the merits of whether this
  project is good or bad.
</p>

<p>
  Robert Brown, owner of Broco Energy. He apologized for the mistake of not notifying abutters. His
  current representative took a leave of absence, and it slipped through the cracks. He noted the
  company&rsquo;s commitment to the community and open communication.
</p>

<p>President Jordan asked if anyone would like to speak in opposition.</p>

<p>
  Several abutters and neighbors addressed the Council regarding the proposed Broco Energy project.
  Mike Rousseau of 9 Burke Street cited ongoing safety concerns, noting that Broco Energy already
  stores fuel in a residential neighborhood and has experienced multiple fires. He described
  frequent fire truck traffic, including tankers and 18-wheelers, as disruptive to neighborhood
  streets, sleep, and quality of life, and urged the Council to deny any permits for additional fuel
  storage before a tragedy occurs. Ken Sear of 7 Norfolk Street stated that his name was not
  included on the abutters notification despite being the property owner and raised safety concerns
  based on past incidents. He emphasized the need to ensure the Fire Department has adequate
  equipment, foam, and apparatus to handle risks associated with oil, propane, and nearby nitrogen
  before the project proceeds. Robert Rousseau of Amesbury, a former abutter and 40-year neighbor of
  the project site, stated that no formal safety studies have been conducted and criticized the
  continued expansion of the business over the years. In response, Bobby Brown, Broco Energy stated
  that the December 12, 2021 incident resulted in significant safety improvements, including new
  infrastructure, increased funding, enhanced firefighting resources, and stronger coordination with
  the Fire Department, noting that while the freight train fire originated outside Lawrence under
  CSX control, the response improved overall preparedness. Hashem Fayed of Broco Energy echoed Mr.
  Brown&rsquo;s remarks, acknowledged and apologized for a mistake, reaffirmed the company&rsquo;s
  commitment to the community, and emphasized ongoing close collaboration with the Fire Department
  to ensure project safety.
</p>

<p>President Jordan closed the hearing.</p>

<p>President Jordan asked council what is your wish.</p>

<p>Motion by Councilor Sullivan to approve the revocation, Second by Councilor Lewandowski</p>

<p>
  Councilor Basiliere stated that he would support the revocation in order to ensure that neighbors
  are properly heard, citing concerns raised by residents in early December and acknowledging Mr.
  Brown&rsquo;s accountability. Councilor Lewandowski noted that similar concerns had been raised
  during a prior permit hearing and acknowledged that while the discussion extended beyond the
  formal scope of the revocation, it was helpful. She expressed appreciation for the
  applicant&rsquo;s accountability and thanked the neighbors for their participation. Council
  President Jordan stated that the matter provided an opportunity to discuss concerns and work
  toward common ground, noting that in his experience on the Council, better outcomes are achieved
  when developers actively work with the surrounding neighborhood.
</p>

<p>
  Motion by Councilor Sullivan to approve the revocation, Second by Councilor Lewandowski<br />
  PASSED &ndash; Yeas 10, Nays 0, Absent 1 (McGonagle)
</p>

<p>President Jordan stated permit revoked.</p>

