<h3>Ms. Rivera: Introduction of Ms. Meletta Bellard, Founder of Jewel&rsquo;s Butterflies, Inc.</h3>

<p>
  Mayor Barrett read a brief statement from the district&rsquo;s attorney regarding this presenter
  and presentation, specifically that there was pending litigation against both the City of
  Haverhill and Haverhill Public Schools. She stated the advice was the following; the inclusion of
  a presenter on the agenda does not constitute endorsement of the presenter's views, claims,
  allegations, or positions by the School Committee, the School District, or the City; the Committee
  will not discuss or comment upon any pending litigation. The mayor noted that the presentation was
  being permitted solely for informational purposes and should not be construed as the adoption of
  any policy position by the Committee. She added that the members should avoid questioning or
  discussion that touches upon matters that may be implicated in the pending lawsuit.
</p>

<p>
  Superintendent Marotta introduced Ms. Bellard, who will inform the committee regarding the newly
  organized organization.
</p>

<p>Ms. Bellard provided an overview of the organization, its mission and progress.</p>

<p>
