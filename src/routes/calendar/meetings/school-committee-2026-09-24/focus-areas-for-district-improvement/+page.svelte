<h2>Preparing to Meet the World</h2>

<p>District improvement thoughts for discussion</p>

<p>
  Thomas Grannemann<br />
  School Committee Member<br />
  Haverhill Public Schools
</p>

<h3>Introduction</h3>

<p>
  Major state investment in school funding through the Student Opportunity Act has enabled Haverhill
  to adopt evidence-based curriculum, close the gap on teacher salaries, support state mandates for
  special education, and provide targeted support in classrooms for high-need students. District
  efforts over the past few years have made a real difference for the students reached by these
  initiatives. Nonetheless, Haverhill Public Schools, like many Gateway City school districts, has
  been slow to recover from COVID disruptions and learning loss. We have seen disappointing overall
  district results in attendance, test scores, and homework completion.
</p>

<p>
  Our persistent problems are not substantially different from those faced by many Gateway City
  districts. So, how can we best build on recent HPS successes and move past the problems that
  continue to plague similar districts? The DESE Multi-tiered System of Support (MTSS) framework is
  both part of the problem and can be part of the solution.
</p>

<p>
  MTSS is intended to get the right level of support to each student. It tells us that higher needs
  students need more supports; some need intensive intervention; some need targeted or occasional
  intervention. HPS has done an excellent job of providing many types of supports, especially
  related to literacy in the lower grades. This includes evidence-based curriculum for the Tier 1
  students, tutoring, WIN block, and intervention for Tier 2, and IEP-guided support for Tier 3.
  This all makes sense given diverse student needs and the importance of reading by third grade in
  longer term student outcomes.
</p>

<p>
  However, MTSS also recognizes, in its large base of the pyramid, the importance of meeting the
  less extensive but real academic and behavioral needs of the large majority of our students in the
  core instructional program. Here Haverhill has had success in adoption of evidence-based
  curriculum in the lower grades and in HHS Classical Academy, CTE, and greater participation and
  passing rates in AP courses. These successes have come from programs that better engage large
  numbers of mainstream students in relevant, challenging academics.
</p>

<p>
  As we consider initiatives for improvement in HPS, we should prioritize strategies that (1) extend
  successful strategies to reach the large majority of our students, (2) effectively engage students
  to take more responsibility for their own education, and (3) prepare students well for life and
  careers in the larger world. I suggest that we prioritize efforts that meet these three criteria
  as we set directions for district improvement.
</p>

<h3>Criteria for focus areas for district improvement</h3>

<h4>Focus on academic initiatives that reach a large majority of students</h4>

<ol>
  <li>
    Statewide performance measures have trended downward for ELA and Math. Improving average and
    median performance measures will require interventions that reach the large numbers of students
    in the middle.
  </li>
  <li>
    If we want to provide opportunities for every student to achieve their potential, we need to
    attend to the needs of the majority of our students in the middle. This is a large and diverse
    group of students.
  </li>
  <li>
    Much focus in HPS has been at two ends of the learning needs scale such as: intensive and
    targeted interventions (lower grades) or in advanced AP classes and Classical Academy (HHS). To
    &ldquo;raise all boats&rdquo; we will need to reach the large majority of students with
    curriculum and teaching in the classroom.
  </li>
  <li>
    Focus as much on identifying and developing individual student strengths as we do on identifying
    and addressing weaknesses through IEPs
  </li>
</ol>

<h4>Focus more on student engagement and responsibility</h4>

<ol>
  <li>
    Research shows that students learn to grow more when they are driven by curiosity to explore and
    are not just coasting or working for grades or test scores.
  </li>
  <li>
    Students need challenges and high expectations with appropriate guidance and support if we they
    are to achieve.
  </li>
  <li>
    In the MTSS framework, students in the largest tier can do more on their own; they are able to
    take a share of responsibilities for their own education and character development.
  </li>
</ol>

<h4>Focus more on preparing our students for the larger world</h4>

<ol>
  <li>We need to offer a program that is clearly meaningful to our students.</li>
  <li>
    Our students will be motivated to show up if, every day they come to school, they experience
    learning something relevant and important for their life and career.
  </li>
  <li>
    Our students, living in eastern Massachusetts, have opportunities for high level work in
    biotech, finance, health care, and information technology. We need to help them prepare for and
    see possibilities.
  </li>
  <li>
    Our students need human skills &ndash; communication, critical thinking, character development
    &ndash; that will continue to be important in an AI-evolving world.
  </li>
</ol>

<h3>Some possible actions steps by HPS priority area</h3>

<h4>Priority 1: Engagement</h4>

<p>Engage students in taking responsibility for their own education</p>

<ul>
  <li>
    We need to convey a clear concise message to our teachers and students that empowers them to
    find how they can best contribute to student academic growth.
  </li>
  <li>
    Encourage students, especially in upper grades, to come to class prepared and ask questions.
  </li>
  <li>
    Selecting a motto such as &ldquo;Preparing to meet the world&rdquo; could apply to our students
    districtwide and invokes responsibility, action, and goals.
  </li>
  <li>Convey high expectations for attendance and homework completion in all grades.</li>
</ul>

<p>
  Give students real information on implications of career choices and preparation needed for
  careers.
</p>

<ul>
  <li>Ensure they know the value of a college education and earnings in different careers.</li>
  <li>
    Ensure they understand their choices for pursuing college 4-yr 2-yr, what upon graduation, what
    later?
  </li>
  <li>
    Develop a program of outside speakers on careers in biotech, information technology, finance,
    health care.
  </li>
</ul>

<p>Help students make better choices on their high school studies</p>

<ul>
  <li>
    Revise the HHS program of studies to provide better guidance on selecting among course of study
    pathways to meet individual goals.
  </li>
  <li>
    Provide for automatic enrollment in honors-level classes based on grades and test scores (with
    opt out possible)
  </li>
</ul>

<p>
  Implement a system for tracking and monitoring active participation in district programs and
  initiatives
</p>

<ul>
  <li>
    Report annually to HSC on the numbers and degree of student involvement by initiatives and MTSS
    tier -- numbers actively engaged and numbers not reached by everything from IEPs, tutoring,
    anti-bulling programs, JROTC, Classical Academy, AP courses, to sports, and clubs.
  </li>
  <li>Ensure programs are reaching all students in all grades.</li>
</ul>

<p>Engage Families</p>

<ul>
  <li>
    Consider a creating a district ombudsman position &ndash; a single point of contact for families
    and staff to link people to solutions and solve problems. This would require empowering an
    individual, with wide knowledge of the district operations and the ear and confidence of the
    superintendent, to cut across
  </li>
</ul>

<h4>Priority 2: Literacy</h4>

<p>Fully evaluate the Wit and Wisdom experience.</p>

<ul>
  <li>Provide HSC with measures of W&amp;W impacts.</li>
  <li>Identify remaining needs and teacher concerns.</li>
  <li>Develop a plan for adjustments and improvements.</li>
</ul>

<p>Assess and address ELA education needs at HHS.</p>

<ul>
  <li>Include challenging source material to build critical thinking skills.</li>
</ul>

<p>Promote independent reading and learning.</p>

<ul>
  <li>
    Encourage independent reading of books in middle and high schools through class assignments and
    book reports.
  </li>
  <li>
    Ensure we have tech-savvy professional librarians with degrees in library science to support
    independent reading at HHS and the middle schools.
  </li>
  <li>
    Provide open school libraries and provide and partner with after-school programs for reading and
    homework completion, including an after-school bus to Haverhill Public Library.
  </li>
</ul>

<h4>Priority 3: Academic Excellence</h4>

<p>Strengthen academic programs for mainstream students.</p>

<ul>
  <li>
    Systematically review curriculum being used in all subjects; where are there needs for updates?
  </li>
  <li>
    Extend evidence-based curriculum to all classes. Ensure up-to-date, evidence-based curriculum in
    all subjects in middle and high schools.
  </li>
</ul>

<p>Expand the more-challenging academic options.</p>

<ul>
  <li>Strengthen and expand AP and honors courses.</li>
  <li>Expand the number of AP classes</li>
  <li>Ensure that most AP course teachers have college instructor-level preparation.</li>
  <li>Encourage students to accumulate a half year or more of college credit in high school.</li>
  <li>Strengthen and expand CTE programs.</li>
  <li>Strengthen curriculum in CTE, with certifications.</li>
  <li>
    Provide $10,000 stipend to STEM and CTE teachers with a graduate degree in area they are
    teaching.
  </li>
  <li>Broaden and expand choices for top level academies at HHS.</li>
</ul>

<p>Strengthen teacher preparation and professional development.</p>

<ul>
  <li>Support teachers graduate education in key subject areas.</li>
  <li>
    Provide $10,000 stipend to AP teachers with a graduate degree (college instructor level
    credentials) in the subject field they are teaching.
  </li>
  <li>Maintain high academic and relevancy standards for lane advancement credits.</li>
  <li>
    Encourage enrollment in the most relevant programs and courses in local and nationally
    recognized universities.
  </li>
  <li>Support teacher time for team planning and curriculum development.</li>
</ul>

<p>Arrange districtwide teacher training in intellectual development of students.</p>

<ul>
  <li>
    Embark on a long-range professional development agenda to support teachers in engaging students
    in developing intellectual and character skills.
  </li>
  <li>
    Year 1: review local and published evidence, then reach out to hear from teachers in PD time and
    structured focus groups on perspectives and challenges of engaging students in academics,
    critical thinking sand character development. What is working, and what does not work, in HPS?
  </li>
  <li>
    Focus on areas such as critical thinking, self-regulated learning, lifelong learning,
    receptivity to feedback, assessing perspective of information sources, ability to recognize
    limits and uncertainty in AI results.
  </li>
  <li>
    Present educational ideals for teachers to draw from, not as added or strict requirements that
    might overburden educators.
  </li>
</ul>

<h4>Priority 4: Readiness for careers and citizenship</h4>

<p>Encourage project-based learning broadly across grade levels and fields of study.</p>

<p>Take full advantage of opportunities to extend STEM and technical education.</p>

<ul>
  <li>Continue to expand CTE.</li>
  <li>Offer more AP classes in STEM areas</li>
  <li>
    Focus on areas with career opportunities in the greater Boston area: Biotech, health care,
    information technology, finance.
  </li>
  <li>Consider extending PLTW courses in more schools, starting in lower grades.</li>
</ul>

<p>Build capacity for strong financial training</p>

<ul>
  <li>
    Build capacity toward offering a mandatory one-semester personal financial literacy course to
    all students.
  </li>
  <li>
    Beyond personal finance, support AP and honors courses in business, economics, and statistics.
  </li>
</ul>

<p>Build capacity for civics- and government-related training</p>

<ul>
  <li>Support enrollment in AP and Honors courses in U.S. Government.</li>
  <li>
    Encourage independent reading in history and biography in history and social studies classes.
  </li>
  <li>
    Encourage local support and broad participation in citizenship related programs such as Model
    UN. Boys State. Girls State, etc.
  </li>
</ul>

<p>Broaden classroom exposure to careers</p>

<ul>
  <li>Bring in outside speakers from different professions in jobs outside the district.</li>
  <li>Hire teachers that bring diverse career experience.</li>
  <li>
    Increase the number of teachers with degrees in field they are teaching (Year 1 document the
    number teachers with degrees in the field they are teaching; Year 2 make hires to increase that
    number.)
  </li>
</ul>

<h4>Priority 5: Financial Management</h4>

<p>Provide for timely development of an estimated aggregate budget each year</p>

<ul>
  <li>
    Report to School Committee on October enrollment as reported to DESE by student funding
    category.
  </li>
  <li>
    In January each year, provide a preliminary aggregate budget amount in advance of DESE release
    of Preliminary Chapter 70 Aid amounts.
  </li>
  <li>
    Preliminary budget to address ongoing operations and adjustments needed to accommodate strategic
    priorities.
  </li>
</ul>

<p>Develop long-run spending estimates for planning</p>

<ul>
  <li>
    Work with School Committee and educators to identify major long-run academic and programmatic
    objectives for the district and specify required organizational and budget needs to achieve
    them.
  </li>
  <li>
    Develop long-run spending estimates based on needs, costs, trends, and enrollment projections.
  </li>
  <li>Provide 5-year rolling budget projections for planning purposes.</li>
</ul>

