<h2>POWERED MICROMOBILITY DEVICE POLICY</h2>

<p>
  The Haverhill School Committee is committed to maintaining a safe environment for students,
  staff,families, and visitors. The increasing use of electric bicycles, motorized scooters,
  electric skateboards,hoverboards, and other motorized micromobility devices presents unique safety
  concerns on school grounds where large numbers of pedestrians may be present. In response to these
  concerns, the Haverhill School Committee adopts this policy as part of its commitment to
  maintaining a safe environment for students, staff, families, and visitors.
</p>

<p>
  All electric and motorized micromobility devices are strictly prohibited on all Haverhill Public
  Schools property owned, leased or controlled. This prohibition applies to all types of devices
  powered, propelled, or assisted by an electric motor or other types of motors. This prohibition
  includes, but is not limited to, roadways, sidewalks,walkways, playgrounds, athletic fields and
  tracks, courtyards, parking lots, driveways, bus loading zones,and any other outdoor area under
  control of the Haverhill Public Schools. For purposes of this policy, a &ldquo;prohibited
  micromobility device&rdquo; shall mean any electrically or motor powered device designed to
  transport one or more persons, including but not limited to the following electric or motorized
  devices: bicycles, scooters, skateboards, hoverboards, unicycles, any substantially similar
  powered personal mobility device.
</p>

<p>
  This definition does not include wheelchairs or other mobility devices used by individuals with
  disabilities.
</p>

<p>
  This prohibition does not apply to conventional, non-motorized bicycles that are powered solely by
  human effort.
</p>

<p>
  At NO time shall a person possess a prohibited micromobility device on school property owned,
  leased, or controlled by the Haverhill Public Schools. This policy shall not apply to:
</p>

<ul>
  <li>
    Mobility devices used by persons with disabilities (including those protected by the Americans
    with Disabilities Act, Section 504 of the Rehabilitations Act, or other applicable law);
  </li>
  <li>
    Law enforcement personnel or emergency responders acting within the scope of their official
    duties;
  </li>
  <li>
    Haverhill Public School employees operating authorized equipment for maintenance or official
    business; or
  </li>
  <li>
    Activities specifically approved by the Superintendent or designed as part of a school-sponsored
    or otherwise approved educational or instructional program.
  </li>
</ul>

<p>
  Failure to comply with this policy will result in referral for appropriate discipline in
  accordance with student or employee conduct and discipline policies, and/or confiscation and/or
  removal of prohibited micromobility devices on school property.
</p>

<p>
  The Superintendent shall develop any rules and regulations necessary to implement this policy.
</p>

