<h2>Petition for Joint or Identical Pole Locations</h2>

<p>North Andover, Massachusetts</p>

<p>To The City Council<br />Of Haverhill, Massachusetts</p>

<p>
  Massachusetts Electric Company d/b/a NATIONAL GRID and Verizon New England, Inc requests
  permission to locate poles, wires, and fixtures, including the necessary sustaining and protecting
  fixtures, along and across the following public way:
</p>

<p>
  North Broadway - National Grid to install 1 JO pole on North Broadway beginning at a point
  approximately 749 feet Northwest of the centerline of the intersection of St. Onge Terrace and
  continuing approximately 15 feet in a West direction. National Grid will install pole 48-84 and
  anchor and guy in public way on North Broadway. The new pole 48-84 to be located approximately
  58&rsquo; Southwest of existing pole 48. New pole 48-84 to provide utilities to new customers at
  416 North Broadway, Haverhill, MA.
</p>

<p>Location approximately as shown on plan attached.</p>

<p>
  Wherefore it prays that after due notice and hearing as provided by law, it be granted a location
  for and permission to erect and maintain poles and wires, together with such sustaining and
  protecting fixtures as it may find necessary, said poles to be erected substantially in accordance
  with the plan filed herewith marked &ndash; North Broadway - Haverhill, Massachusetts.
</p>

<p>No.# 31355845</p>

<p>
  Also, for permission to lay and maintain underground laterals, cables, and wires in the above or
  intersecting public ways for the purpose of making connections with such poles and buildings as
  each of said petitioners may desire for distributing purposes.
</p>

<p>
  Your petitioner agrees to reserve space for one cross-arm at a suitable point on each of said
  poles for the fire, police, telephone, and telegraph signal wires belonging to the municipality
  and used by it exclusively for municipal purposes.
</p>

<h2>Order for Joint or Identical Pole Locations</h2>

<p>August 27, 2026</p>

<p>To the City Council Of Haverhill, Massachusetts</p>

<p>
  Notice having been given and public hearing held, as provided by law, IT IS HEREBY ORDERED: that
  Massachusetts Electric Company d/b/a NATIONAL GRID and VERIZON NEW ENGLAND INC. (formerly known as
  NEW ENGLAND TELEPHONE AND TELEGRAPH COMPANY) be and they are hereby granted joint or identical
  locations for and permission to erect and maintain poles and wires to be placed thereon, together
  with such sustaining and protecting fixtures as said Companies may deem necessary, in the public
  way or ways hereinafter referred to, as requested in petition of said Companies dated the 26th day
  of August, 2026.
</p>

<p>All construction under this order shall be in accordance with the following conditions:</p>

<p>
  Poles shall be of sound timber, and reasonable straight, and shall be set substantially at the
  points indicated upon the plan marked &ndash; North Broadway - Haverhill, Massachusetts.
</p>

<p>No.# 31355845</p>

<p>Filed with this order:</p>

<p>
  There may be attached to said poles by Massachusetts Electric Company d/b/a NATIONAL GRID and
  Verizon New England Inc. such wires, cables, and fixtures as needed in their business and all of
  said wires and cables shall be placed at a height of not less than twenty (20) feet from the
  ground.
</p>

<p>
  The following are the public ways or part of ways along which the poles above referred to may be
  erected, and the number of poles which may be erected thereon under this order:
</p>

<p>
  North Broadway - National Grid to install 1 JO pole on North Broadway beginning at a point
  approximately 749 feet Northwest of the centerline of the intersection of St. Onge Terrace and
  continuing approximately 15 feet in a West direction. National Grid will install pole 48-84 and
  anchor and guy in public way on North Broadway. The new pole 48-84 to be located approximately
  58&rsquo; Southwest of existing pole 48. New pole 48-84 to provide utilities to new customers at
  416 North Broadway, Haverhill, MA.
</p>

<p>
  Also, for permission to lay and maintain underground laterals, cables, and wires in the above or
  intersecting public ways for the purpose of making connections with such poles and buildings as
  each of said petitioners may desire for distributing purposes.
</p>
