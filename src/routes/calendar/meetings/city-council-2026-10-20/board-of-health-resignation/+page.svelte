<h2>Letter from Mayor Melinda E. Barrett, October 15, 2026</h2>

<p>RE: Board Of Health Resignation&ndash; Dr. Romie Mundy</p>

<p>
  I would like to inform you that effective October 15, 2026, Dr. Romie Mundy has resigned from the
  Board of Health. His letter is attached for your review.
</p>

<h2>Email from Romie Mundy, Resignation from Board of Health</h2>

<p>Dear Mayor,</p>

<p>
  Please accept this email as notice of my resignation from the Board of Health after approximately
  ten years of service. It has been a privilege to assist the city in this role and to contribute in
  a small way to the health and well-being of our community during that time.
</p>

<p>
  As you know, I currently hold an active medical license and, to my knowledge, am the only member
  of city government in that position. In that capacity, I have been providing medical oversight for
  the city nurse, Mary Connelly, particularly with respect to the city&rsquo;s vaccine program. I
  would be glad to continue offering that oversight in an informal advisory capacity, if helpful,
  until another member with an active medical license is appointed.
</p>

<p>
  Recognizing that the Board consists of only three members and that it may take some time to
  identify a replacement, I am also willing to continue serving for a transitional period of
  approximately three to six months to allow for a smooth transition if that would be helpful.
</p>

<p>Thank you again for the opportunity to serve the city in this capacity.</p>
