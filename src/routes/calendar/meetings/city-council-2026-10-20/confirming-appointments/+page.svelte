<h2>Letter from Alexandra Filippakis, D.O., October 07, 2026</h2>

<p>
  I am writing to express my interest in serving on the Haverhill Board of Health. I am a
  board-certified neurologist and have practiced in Haverhill since April 2025 as the owner of
  Greenleaf Neurology, PLLC. I would welcome the chance to put that clinical experience to work for
  the city&rsquo;s public health.
</p>

<p>
  Much of what I see in the clinic begins upstream of the exam room. Stroke outcomes depend on how
  quickly residents recognize symptoms and reach care. Concussions in youth and school sports often
  go unreported. Dementia increasingly shapes how families, housing and emergency services function.
  Childhood lead exposure, still a concern in older housing stock, causes neurological harm that
  cannot be reversed. These are public health problems as much as clinical ones, and I would bring a
  specialist&rsquo;s perspective to them.
</p>

<p>
  I also understand that a Board of Health&rsquo;s day-to-day work is largely regulatory: housing
  and sanitary code, food establishments, septic systems, tobacco and nicotine sales, and disease
  control. I am prepared to learn that work thoroughly, to read the record before each meeting, and
  to rely on the Health Department&rsquo;s professional staff. My aim would be sound, evidence-based
  decisions that residents can trust.
</p>

<p>
  Running a small medical practice has taught me to weigh costs, read regulations closely, and make
  decisions that affect real people&rsquo;s access to care. I also serve as the President of the
  Greenleaf Neurological Foundation, a non-profit focused on neurological research and public
  education. Should any matter before the Board involve my practice or the foundation, I would
  disclose it and recuse myself as the state conflict-of-interest law requires.
</p>

<p>
  Thank you for considering my interest. I would be glad to meet with you or to provide my CV and
  references.
</p>
