<h2>
  An Ordinance Relating to Amending Chapter 255, Zoning, by Adding a New Section 7.9, Temporary
  Moratorium on Batter Energy Storage Systems
</h2>

<p>
  BE IT ORDAINED by the City Council of the City of Haverhill that Chapter 255, Zoning, of the Code
  of the City of Haverhill, as amended, being and is hereby further amended as follows by inserting
  the following new section 7.9 Temporary Moratorium on Battery Energy Storage Systems:
</p>

<h3>&sect;7.9 TEMPORARY MORATORIUM ON BATTERY ENERGY STORAGE SYSTEMS</h3>

<p>&sect; 7.9.1 Purpose.</p>

<p>
  This Ordinance adopted pursuant to Zoning Act, G.L. c. 40A, as amended, Section 2A of 1975 Mass.
  Acts 808, and by Article 89 of the Amendments to the Constitution of the Commonwealth of
  Massachusetts for the purpose of protecting the public health and welfare of the residents of
  Haverhill and provide time to adopt an appropriate and effective zoning ordinance to regulate the
  installation and use of free-standing battery energy storage systems (&ldquo;BESS&rdquo;).
  Specifically, this moratorium will enable the City to research appropriate areas of the City which
  include sufficient land mass, access to utilities, conserving the City&rsquo;s available open
  space and forested lands, impacts to the Merrimack River, which is a drinking water source for
  communities in the Merrimack River watershed, all in order to adopt an appropriate and effective
  zoning ordinance permitting BESS facilities.
</p>

<p>&sect; 7.9.2 Moratorium.</p>

<p>
  For the reasons set forth above and notwithstanding any other provision of the Zoning Ordinance to
  the contrary, the City hereby adopts a temporary moratorium on the permits for and use of land for
  BESS. The moratorium shall be in effect for twenty-four (24) months following the effective date
  of this amendment. During the moratorium period, the City shall undertake a planning process to
  address the potential impacts of BESS and related uses and shall consider adopting new Zoning
  Ordinances to better address the impact and construction of same in the City.
</p>

