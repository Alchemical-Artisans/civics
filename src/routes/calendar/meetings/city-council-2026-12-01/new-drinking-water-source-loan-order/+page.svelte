<h2>Letter from the Mayor</h2>

<p>
  I respectfully submit an Order to amend the loan order which was approved on October 11, 2016 in
  the amount of $17,168,750.00 and increase the amount appropriated to $26,075,850.00 to construct
  the well at 309 East Broadway.
</p>

<p>I recommend approval.</p>

<h2>Order</h2>

<p>ORDERED:</p>

<p>
  That the order adopted by the City Council on October 11, 2016, which authorized $17,168,750 for
  the planning, engineering, and construction of improvements to develop a new drinking water
  source, be amended to increase the amount appropriated and authorized to be borrowed to a new
  aggregate total of $26,075,850, so that the amended loan order reads as follows:
</p>

<blockquote>
  <p>
    ORDERED: &ldquo;That $26,075,850 is appropriated for the purpose of financing the planning,
    engineering, and construction of improvements to develop a new drinking water source, including
    the payment of all costs incidental or related thereto, and including without limitation all
    costs thereof as defined in Section 1 of Chapter 29C of the General Laws, as most recently
    amended (&ldquo;Chapter 29C&rdquo;); that to meet this appropriation, the Treasurer with the
    approval of the Mayor is authorized to borrow $26,075,850 and issue bonds or notes therefor
    under Chapter 44 of the General Laws and/or Chapter 29C or any other enabling authority; that
    such bonds or notes shall be general obligations of the City unless the Treasurer with the
    approval of the Mayor determines that they should be issued as limited obligations and may be
    secured by local system revenues as defined in Section 1 of Chapter 29C; that the Treasurer with
    the approval of the Mayor is authorized to borrow all or a portion of such amount from the
    Massachusetts Clean Water Trust established pursuant to Chapter 29C (the &ldquo;Trust&rdquo;),
    and in connection therewith to enter into a financing agreement and/or a security agreement with
    the Trust and otherwise to contract with the Trust and the Department of Environmental
    Protection with respect to such loan and for any federal or state aid available for the project
    or for the financing thereof; and that the Mayor is authorized to enter into a project
    regulatory agreement with the Department of Environmental Protection, to expend all funds
    available for the project and to take any other action necessary or convenient to carry out the
    project.
  </p>
  <p>
    FURTHER ORDERED: That the Treasurer is authorized to file an application with the appropriate
    officials of The Commonwealth of Massachusetts (the &ldquo;Commonwealth&rdquo;) to qualify under
    Chapter 44A of the General Laws any and all bonds of the City authorized by this order, and to
    provide such information and execute such documents as such officials of the Commonwealth may
    require in connection therewith. The Mayor is authorized to apply for and accept any and all
    grants that may be available to pay the costs of this project, and the total borrowing
    authorized by this order shall be reduced to the extent of any such grants received by the City
    for this project.&rdquo;
  </p>
</blockquote>

