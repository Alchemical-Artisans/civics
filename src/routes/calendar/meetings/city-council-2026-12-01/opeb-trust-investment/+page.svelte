<h2>Letter from the Mayor</h2>

<p>I respectfully submit an Order to authorize investment of OPEB trust funds.</p>

<p>I recommend approval.</p>

<h2>Order</h2>

<p>
  It is hereby Ordered that the City Council of the City of Haverhill does adopt and hereby approve
  the following actions to be taken by the Treasurer of the City of Haverhill and President of the
  Council and further approve the following:
</p>

<p>
  Whereas the Treasurer of the City of Haverhill, as Custodian of the OPEB Fund, be, and hereby is,
  authorized to execute and deliver the Investment Agreement with the State Retiree Benefits Trust
  Fund board of trustees on behalf of the City of Haverhill for the purpose of making the
  representations and warranties, acknowledgements and agreements on the part of the City of
  Haverhill to be made and performed thereunder; and
</p>

<p>
  Whereas the President of the City of Council of the City of Haverhill shall certifies to the State
  Retiree Benefits Trust Fund Board of Trustees and the Pension Reserves Investment Management Board
  that he is the duly elected President of the City Council, the Governmental Unit and authorized to
  execute the Incumbency Certificate related to the Investment Agreement with the State Retiree
  Benefits Trust Fund board of trustees on behalf of the City of Haverhill; and
</p>

<p>
  Whereas, to the extent required, the City Council does hereby authorize the City Treasurer and the
  OPEB Trust to invest the OPEB Trust funds in the State Retiree Benefits Trust Fund pursuant to the
  Investment Agreement.
</p>

<p>So voted.</p>

