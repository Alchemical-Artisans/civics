<h2>Letter from the Mayor</h2>

<p>
  <strong>
    RE: Order Authorizing the City Council to Accept a Gift of $1500.00 from Breakfast Exchange Club
    of Haverhill
  </strong>
</p>

<p>
  Please see the attached order authorizing the City Council to accept a gift of $1500.00 dollars
  from the Breakfast Exchange Club of Haverhill for the Council on Aging Department&rsquo;s Happy
  Rides program.
</p>

<p>I recommend approval.</p>

<h2>Gift Acceptance</h2>

<p>
  At a regularly convened meeting of the City Council of the City of Haverhill, held on the 1st day
  of December 2026, it was voted as follows:
</p>

<p>
  That the City Council of the City of Haverhill duly elected, qualified, and acting as such, on
  behalf of the City votes to accept a gift of fifteen hundred dollars ($1,500.00) for the Happy
  Rides program. Consistent with the purpose of the donation, as stated in the letter from the
  Breakfast Exchange Club addressed to the City of Haverhill dated November 2026, the Gift shall be
  used by the Council on Aging Department.
</p>

