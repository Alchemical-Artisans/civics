<h2>Letter from the Mayor</h2>

<p>
  I respectfully submit an Order to accept the Golden Hill Elementary School Playground as a gift
  from the Haverhill Playground Committee.
</p>

<p>I recommend approval.</p>

<h2>Gift Acceptance</h2>

<p>
  At a regularly convened meeting of the City Council of the City of Haverhill, held on the 1<sup
    >st</sup
  > day of December, 2026, it was voted as follows:
</p>

<p>
  That the City Council of the City of Haverhill, duly elected, qualified, and acting as such, on
  behalf of the City votes to accept the completed Golden Hill Elementary School Playground as a
  gift from the Haverhill Community Playground Committee, which gift was previously accepted by the
  Haverhill School Committee at its meeting on November 19, 2026, pursuant to the Memorandum of
  Understanding between the parties, acknowledging receipt of the independent safety inspection
  certification and fall attenuation testing certification required by Section 8 of the Memorandum
  of Understanding, and with a retail value of $450,000.00.
</p>

