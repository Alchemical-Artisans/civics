<!--
  Eight phases drawn across two pages as four arrows each, with a month printed
  under every one. The months are part of the phase rather than a heading, so
  they get a column instead of being folded into the prose.
-->
<table>
  <thead>
    <tr>
      <th scope="col">Phase</th>
      <th scope="col">When</th>
      <th scope="col">What happens</th>
    </tr>
  </thead>
  <tbody>
    <tr>
      <th scope="row">Revenue Projections</th>
      <td>January</td>
      <td>
        The Mayor and the Budget Team convene to evaluate current revenues, explore potential new
        revenue streams, and forecast estimated revenue for the upcoming fiscal year.
      </td>
    </tr>
    <tr>
      <th scope="row">Budget Directives</th>
      <td>January</td>
      <td>
        The Mayor provides budget directives to department heads for the purpose of developing and
        submitting their operating and capital budget requests.
      </td>
    </tr>
    <tr>
      <th scope="row">Budget Review</th>
      <td>February</td>
      <td>
        Mayor &amp; Budget Team meet with departments to review budget requests and determine
        priorities. Revenue estimates are updated and the maximum available budget is determined.
      </td>
    </tr>
    <tr>
      <th scope="row">State Budget</th>
      <td>January-July</td>
      <td>
        The State budget process begins in January and is typically finalized in July. The
        Governor's Office and the Legislature work together to pass a fiscally responsible budget
        each year.
      </td>
    </tr>
    <tr>
      <th scope="row">Mayor's Budget</th>
      <td>May</td>
      <td>
        The Mayor's final budget is submitted to the City Council. The council then has 45 days to
        either approve, reduce, or reject the Mayor's operating budget.
      </td>
    </tr>
    <tr>
      <th scope="row">City Council Budget Hearings</th>
      <td>May/June</td>
      <td>
        The City Council conducts public budget hearings, reviewing the proposed budget presented by
        the Mayor with each city department.
      </td>
    </tr>
    <tr>
      <th scope="row">Budget Adoption</th>
      <td>June</td>
      <td>
        City Council votes to adopt a budget by June 30th. If a budget is not adopted, the Mayor may
        submit a "continuing appropriation budget" on a month-to-month basis for a period not to
        exceed three months.
      </td>
    </tr>
    <tr>
      <th scope="row">Budget Implementation</th>
      <td>July-June</td>
      <td>
        The Auditor's Office enters the new operating budget into the ledger and initiates regular
        monitoring and reporting of revenues, expenditures, and compliance issues.
      </td>
    </tr>
  </tbody>
</table>
