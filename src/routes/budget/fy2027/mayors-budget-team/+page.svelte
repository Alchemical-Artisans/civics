<p>
  When Mayor Barrett took office, she established a "Budget Team" comprising members from both the
  City Council and the School Committee. This initiative, new to the city, aimed to create a
  budgeting process that is collaborative, transparent, and impactful, taking into account both
  long- and short-term objectives while optimizing resource use.
</p>

