<p>
  Located 28 miles north of Boston along the Merrimack River, Haverhill is one of the state's
  largest and most geographically diverse communities, with farming areas, dense urban
  neighborhoods, multiple commercial and residential villages, and a bustling downtown featuring
  celebrated restaurant and arts districts. The city is one of the oldest historic communities in
  the state. Established in 1640 as Pentucket, Haverhill was incorporated as a city in 1870.
  Although originally settled as farmland, the city evolved into a major industrial center through
  the establishment of saw and grist mills in the late 17th century, tanneries and boat yards in the
  early 18th century and shoe manufacturing, its leading industry for 180 years. Currently, computer
  technology and research industries thrive within Haverhill's seven industrial parks, business
  districts, and newly rehabilitated central business district.
</p>
