import { describe, it, expect } from "vitest"
import { fitRidgeRegression, predict } from "./regression.mjs"

/** A small seeded PRNG (mulberry32), matching the placeholder generators. */
function mulberry32(seed) {
  let a = seed
  return function random() {
    a |= 0
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), a | 1)
    t = (t + Math.imul(t ^ (t >>> 7), t | 61)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

describe("fitRidgeRegression", () => {
  it("recovers known coefficients from data generated by a known linear equation", () => {
    // y = 2 + 3*x1 - 1.5*x2 + tiny noise -- if the solver is right, fitting
    // this should land very close to [3, -1.5] and an intercept near 2,
    // however the water data itself behaves.
    const random = mulberry32(1)
    const X = []
    const y = []
    for (let i = 0; i < 500; i++) {
      const x1 = random() * 10 - 5
      const x2 = random() * 10 - 5
      const noise = (random() - 0.5) * 0.01
      X.push([x1, x2])
      y.push(2 + 3 * x1 - 1.5 * x2 + noise)
    }

    const model = fitRidgeRegression(X, y, 0.001)
    expect(model.coefficients[0]).toBeCloseTo(3, 1)
    expect(model.coefficients[1]).toBeCloseTo(-1.5, 1)
    expect(model.intercept).toBeCloseTo(2, 1)
    expect(model.rSquared).toBeGreaterThan(0.999)
  })

  it("predicts new rows consistently with the fit it returns", () => {
    const X = [
      [0, 0],
      [1, 0],
      [0, 1],
      [1, 1],
      [2, 1],
    ]
    const y = [1, 3, 0, 2, 4]
    const model = fitRidgeRegression(X, y, 0.01)

    for (let i = 0; i < X.length; i++) {
      expect(predict(model, X[i])).toBeCloseTo(
        model.intercept + X[i][0] * model.coefficients[0] + X[i][1] * model.coefficients[1],
        10,
      )
    }
  })

  it("shrinks toward zero as lambda grows, and toward plain least squares as it shrinks", () => {
    const random = mulberry32(2)
    const X = []
    const y = []
    for (let i = 0; i < 200; i++) {
      const x1 = random() * 10 - 5
      X.push([x1])
      y.push(5 * x1 + (random() - 0.5) * 0.1)
    }

    const looseFit = fitRidgeRegression(X, y, 0.0001)
    const heavilyPenalized = fitRidgeRegression(X, y, 10_000)

    expect(Math.abs(looseFit.coefficients[0])).toBeGreaterThan(
      Math.abs(heavilyPenalized.coefficients[0]),
    )
    expect(looseFit.coefficients[0]).toBeCloseTo(5, 1)
  })

  it("refuses mismatched row counts rather than fitting something meaningless", () => {
    expect(() => fitRidgeRegression([[1], [2]], [1])).toThrow()
  })
})
